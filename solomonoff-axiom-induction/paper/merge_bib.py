#!/usr/bin/env python3
"""Merge the paper's bibliography into bib/all.bib (generated; never edit all.bib by hand).

Sources, in priority order (the first source that has a key supplies its entry):
  1. bib/*.bib except all.bib, in sorted file-name order (the paper's own, checked entries;
     see bib/bib-report.md once it exists);
  2. ../research/refs.bib, the merged research bibliography, as a FALLBACK only, so that a key
     cited by a section resolves before the paper's own bibliography has an entry for it.

Report (printed): entry counts per source, keys whose duplicate entries differ in title, keys cited
in sections/*.tex that no source has, and cited keys that are supplied only by the fallback (these
still need an entry in bib/*.bib, i.e. a check by the bibliography editor, before the paper is final).
"""
import glob
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
FALLBACK = os.path.normpath(os.path.join(here, '..', 'research', 'refs.bib'))


def entries_of(text):
    """Yield (kind, key, full_entry_text) for every @kind{key, ...} entry, by brace matching."""
    for m in re.finditer(r'(?m)^@(\w+)\s*\{\s*([^,\s]+)\s*,', text):
        kind, key = m.group(1), m.group(2)
        if kind.lower() in ('comment', 'preamble', 'string'):
            continue
        depth, i = 0, text.index('{', m.start())
        start = m.start()
        while i < len(text):
            ch = text[i]
            if ch == '{':
                depth += 1
            elif ch == '}':
                depth -= 1
                if depth == 0:
                    break
            i += 1
        yield kind, key, text[start:i + 1]


def title_of(entry):
    t = re.search(r'(?im)^\s*title\s*=\s*[{"](.*?)[}"]\s*,?\s*$', entry)
    return t.group(1).lower().replace('{', '').replace('}', '').strip() if t else None


entries, order, origin, conflicts = {}, [], {}, []
sources = [f for f in sorted(glob.glob(os.path.join(here, 'bib', '*.bib')))
           if not f.endswith(os.sep + 'all.bib')]
if os.path.exists(FALLBACK):
    sources.append(FALLBACK)
counts = {}
for f in sources:
    tag = 'FALLBACK research/refs.bib' if f == FALLBACK else 'bib/' + os.path.basename(f)
    counts[tag] = 0
    text = open(f, encoding='utf-8').read()
    for kind, key, full in entries_of(text):
        if key in entries:
            a, b = title_of(entries[key]), title_of(full)
            if a and b and a != b:
                conflicts.append((key, tag))
            continue
        entries[key] = full
        order.append(key)
        origin[key] = tag
        counts[tag] += 1

with open(os.path.join(here, 'bib', 'all.bib'), 'w', encoding='utf-8') as out:
    out.write('% Generated by merge_bib.py from bib/*.bib (priority) and ../research/refs.bib (fallback);\n'
              '% do not edit by hand.\n\n')
    for k in order:
        out.write(entries[k].rstrip() + '\n\n')

cited = set()
cite_re = re.compile(r'\\(?:no)?cite[a-zA-Z]*\*?(?:\[[^\]]*\]){0,2}\{([^}]*)\}')
for f in glob.glob(os.path.join(here, 'sections', '*.tex')) + [os.path.join(here, 'main.tex')]:
    if not os.path.exists(f):
        continue
    for line in open(f, encoding='utf-8'):
        line = re.sub(r'(?<!\\)%.*', '', line)
        for m in cite_re.finditer(line):
            for k in m.group(1).split(','):
                if k.strip() and k.strip() != '*':
                    cited.add(k.strip())
missing = sorted(k for k in cited if k not in entries)
fallback_only = sorted(k for k in cited if origin.get(k, '').startswith('FALLBACK'))

print(f'{len(order)} entries ({", ".join(f"{t}: {n}" for t, n in counts.items())}); '
      f'{len(conflicts)} title conflicts: {conflicts[:20]}')
print(f'cited keys: {len(cited)}; missing everywhere: {len(missing)} {missing[:40]}')
print(f'cited keys supplied only by the fallback: {len(fallback_only)} {fallback_only[:60]}')
