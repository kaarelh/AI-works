#!/usr/bin/env python3
"""Adversarial checks for Section 2 of research/prove-b/hellinger-runs.md (Lemma L4).

Everything is exact (finite trees, all leaves enumerated) up to floating point.

Notation of the target file: P, Q laws of (X_1..X_n) generated by kernels p_i, q_i;
h_i = H^2(p_i, q_i)(history) = 1 - sum sqrt(p q);  sigma := E_P sum_i h_i;
H2 = 1 - BC(P,Q);  TV = (1/2) sum |P - Q|.

Parts
 (A) search for a violation of  H2 <= c* sigma  (c* = 2.964147...) and of H2 <= 4 sigma
     on general trees (every history has its own pair of kernels; exact zeros allowed).
 (B) identity (a) and the two-sided bound (b) of Theorem 2.1 on the same trees.
 (C) NEW (this report): the direct bound  TV <= sigma + sqrt(sigma^2 + 2 sigma)  (<= 2 sqrt(sigma)
     for sigma <= 1/4), from the potentials U_m(x) = (m-x)_+^2/(m^2-1); search for a violation, and
     comparison with the file's TV <= sqrt(8 sigma) and sqrt(2 c* sigma).
 (D) NEW: for the event Z = {Q-density zero},  P(Z) <= 2 sigma  (the file has 2 H2 <= 8 sigma).
 (E) the one-step inequality behind (C) on extreme laws, and Step 2 of Theorem 2.7 in
     50-digit arithmetic at random points (independent of the checker's grid).

Run:  python3 hellinger-runs_attack_l4.py            (about 15 minutes)
"""
import sys, math, time
import numpy as np
from scipy.optimize import minimize

rng = np.random.default_rng(20261115)
CSTAR = 2.96414715730767803

# ---------------------------------------------------------------- tree evaluator
def unpack(theta, D, b):
    """theta -> lists p[i], q[i] of shape (b**i, b); squares normalised, so exact zeros are reachable."""
    ps, qs, k = [], [], 0
    for i in range(D):
        m = b ** i
        a = theta[k:k + m * b].reshape(m, b) ** 2 + 1e-300; k += m * b
        c = theta[k:k + m * b].reshape(m, b) ** 2 + 1e-300; k += m * b
        ps.append(a / a.sum(1, keepdims=True)); qs.append(c / c.sum(1, keepdims=True))
    return ps, qs

def nparams(D, b):
    return sum(2 * b ** i * b for i in range(D))

def stats(ps, qs):
    """returns H2, sigma_P, sigma_Q, TV, sum_P Lam h, P(Q-density = 0)"""
    P = np.ones(1); Q = np.ones(1)
    sigP = sigQ = lamh = 0.0
    for p, q in zip(ps, qs):
        h = 0.5 * ((np.sqrt(p) - np.sqrt(q)) ** 2).sum(1)  # = 1 - sum sqrt(p q), without cancellation
        sigP += float((P * h).sum()); sigQ += float((Q * h).sum())
        lamh += float((np.sqrt(P * Q) * h).sum())          # E_P[Lam_{i-1} h_i] = sum sqrt(P Q) h
        P = (P[:, None] * p).reshape(-1); Q = (Q[:, None] * q).reshape(-1)
    H2 = 0.5 * float(((np.sqrt(P) - np.sqrt(Q)) ** 2).sum())
    TV = 0.5 * float(np.abs(P - Q).sum())
    Z = float(P[Q < 1e-200].sum())
    return H2, sigP, sigQ, TV, lamh, Z

def tvbound(s):
    return min(1.0, s + math.sqrt(s * s + 2 * s))

def random_theta(D, b, sparse):
    th = rng.normal(size=nparams(D, b))
    if sparse > 0:
        th[rng.random(th.size) < sparse] = 0.0
    return th

def fix_zero_rows(theta, D, b):
    # a row of all zeros would give 0/0; replace by a uniform row
    k = 0
    for i in range(D):
        for _ in range(2):
            m = b ** i
            blk = theta[k:k + m * b].reshape(m, b)
            bad = (np.abs(blk).sum(1) == 0)
            blk[bad] = 1.0
            k += m * b
    return theta

# ---------------------------------------------------------------- (A),(B),(C),(D) random trees
def part_random(nrep=4000):
    worst = dict(r=0.0, ident=0.0, two=-1e9, tv=0.0, tvsqrt=0.0, z=0.0, tv_old=0.0)
    for rep in range(nrep):
        D = int(rng.integers(1, 6)); b = int(rng.integers(2, 4))
        if b == 3 and D > 4: D = 4
        th = fix_zero_rows(random_theta(D, b, sparse=rng.choice([0.0, 0.2, 0.5])), D, b)
        H2, sP, sQ, TV, lamh, Z = stats(*unpack(th, D, b))
        if sP > 1e-12:
            worst['r'] = max(worst['r'], H2 / sP)
            worst['tv'] = max(worst['tv'], TV / tvbound(sP))
            worst['tvsqrt'] = max(worst['tvsqrt'], TV / math.sqrt(sP))
            worst['z'] = max(worst['z'], Z / sP)
        worst['ident'] = max(worst['ident'], abs(H2 - lamh))
        worst['two'] = max(worst['two'], H2 - 0.5 * (sP + sQ))
    return worst

# ---------------------------------------------------------------- optimisation
def optimise(obj, D, b, nstart, sparse=0.0, maxiter=300):
    best = -1e9; bestth = None
    for s in range(nstart):
        th0 = fix_zero_rows(random_theta(D, b, sparse), D, b)
        f = lambda th: -obj(th, D, b)
        try:
            res = minimize(f, th0, method='L-BFGS-B', bounds=[(-30.0, 30.0)] * th0.size,
                           options=dict(maxiter=maxiter, maxfun=200000))
            val = -res.fun; th = res.x
        except Exception as e:           # pragma: no cover
            continue
        if val > best: best, bestth = val, th
    return best, bestth

def obj_ratio(th, D, b):
    H2, sP, sQ, TV, lamh, Z = stats(*unpack(th, D, b))
    if sP < 1e-12:           # sigma = 0 up to rounding: P = Q and both sides vanish; no ratio is defined
        return 0.0
    return H2 / sP

def obj_tv(th, D, b):
    H2, sP, sQ, TV, lamh, Z = stats(*unpack(th, D, b))
    return TV / max(tvbound(sP), 1e-300) if sP < 0.25 else TV - 10 * (sP - 0.25)

def obj_tvsqrt(th, D, b):
    H2, sP, sQ, TV, lamh, Z = stats(*unpack(th, D, b))
    return TV / math.sqrt(max(sP, 1e-300))

def make_obj_tv_at(s0):
    # maximise TV subject to sigma <= s0 (penalty): traces the curve F(s0) = sup TV at given sigma
    def f(th, D, b):
        H2, sP, sQ, TV, lamh, Z = stats(*unpack(th, D, b))
        return TV - 200.0 * max(0.0, sP - s0)
    return f

def obj_z(th, D, b):
    # smooth surrogate for P(Q-density = 0): P-mass of leaves where Q/P is tiny
    ps, qs = unpack(th, D, b)
    P = np.ones(1); Q = np.ones(1); sP = 0.0
    for p, q in zip(ps, qs):
        h = 0.5 * ((np.sqrt(p) - np.sqrt(q)) ** 2).sum(1); sP += float((P * h).sum())
        P = (P[:, None] * p).reshape(-1); Q = (Q[:, None] * q).reshape(-1)
    singular = 1.0 - float(np.minimum(P, 1e6 * Q).sum())   # ~ P(Q = 0) when Q is exactly 0 there
    if sP < 1e-12:
        return 0.0
    return singular / sP

# ---------------------------------------------------------------- (E) one-step checks
def onestep_tv_potential():
    """max over extreme laws of E U_m(Lam r) - U_m(Lam) - c_m (1 - E r), U_m = (m-x)_+^2/(m^2-1), c_m = 2m^2/(m^2-1);
    and min over x of U_m(x) - (1 - x^2)_+ ."""
    worst = -1e9; worst_dom = 1e9
    for m in [1.01, 1.1, 1.5, 2.0, 3.0, 10.0]:
        g = 2.0 / (m * m - 1); c = g * m * m
        U = lambda x: 0.5 * g * np.maximum(m - x, 0.0) ** 2
        xs = np.linspace(0, 3 * m, 200001)
        worst_dom = min(worst_dom, float((U(xs) - np.maximum(1 - xs ** 2, 0)).min()))
        for Lam in np.concatenate([np.linspace(0.0, 2 * m, 81), np.geomspace(2 * m, 1e3, 20)]):
            # point masses r <= 1
            r = np.linspace(0, 1, 2001)
            worst = max(worst, float((U(Lam * r) - U(Lam) - c * (1 - r)).max()))
            # two-point laws with E r^2 = 1: r1 <= 1 <= r2
            r1 = np.linspace(0, 1, 401)[:, None]; r2 = np.geomspace(1.0, 1e3, 400)[None, :] + 1e-12
            w2 = (1 - r1 ** 2) / (r2 ** 2 - r1 ** 2); w1 = 1 - w2
            val = w1 * U(Lam * r1) + w2 * U(Lam * r2) - U(Lam) - c * (1 - (w1 * r1 + w2 * r2))
            worst = max(worst, float(val.max()))
    return worst, worst_dom

def step2_highprec(npts=4000):
    import mpmath as mp
    mp.mp.dps = 50
    g = lambda q: 1 + q * mp.e ** (q * q / 4) * (1 / mp.sqrt(2) + mp.sqrt(mp.pi) / 2 * mp.erf(q / 2))
    k = lambda q: 1 / (1 - q * q / 2)
    q0 = mp.findroot(lambda q: g(q) - k(q), mp.mpf('1.1512'))
    c = k(q0); s0 = 1 / c
    def q_of_s(s):
        if s >= 1: return mp.mpf(0)
        if s <= s0: return q0
        return mp.findroot(lambda q: 1 / g(q) - s, (mp.mpf('1e-30'), q0), solver='anderson', tol=mp.mpf(10) ** (-45))
    def pqr(s):
        if s >= 1: return mp.sqrt(2), mp.mpf(0), 1 / mp.sqrt(2)
        q = q_of_s(s); p = 2 * (1 - s) / q
        return p, q, (p - q) / 2
    def V(x):
        if x <= 1: return mp.mpf(0)
        if x >= c: return x - c / 2
        return c * pqr(x / c)[2] ** 2
    def tau(Lam, a):
        if Lam <= 1:
            mu = (c - Lam) / 2
        elif Lam >= c:
            mu = c / 2
        else:
            mu = c * pqr(Lam / c)[0] ** 2 / 4
        U = V(Lam) - Lam
        return U + c * (1 - a / Lam) + mu * (a * a / (Lam * Lam) - 1) + a
    worst = mp.mpf(10)
    r = np.random.default_rng(7)
    for i in range(npts):
        mode = i % 4
        if mode == 0:   Lam = mp.mpf(float(r.uniform(0.01, 5))); a = mp.mpf(float(r.uniform(0, 8)))
        elif mode == 1: Lam = mp.mpf(float(r.uniform(1, float(c)))); a = Lam * mp.mpf(float(r.uniform(0.9, 1.1)))   # near the tangency a = Lam
        elif mode == 2: Lam = mp.mpf(float(np.exp(r.uniform(-6, 6)))); a = mp.mpf(float(np.exp(r.uniform(-6, 6))))
        else:           Lam = mp.mpf(float(r.choice([1.0, float(c)]) * (1 + r.uniform(-1e-6, 1e-6)))); a = mp.mpf(float(r.uniform(0, 6)))
        d = tau(Lam, a) - V(a)
        if d < worst: worst = d; arg = (float(Lam), float(a))
    return q0, c, worst, arg

# ---------------------------------------------------------------- main
if __name__ == '__main__':
    t0 = time.time()
    w = part_random()
    print("(A,B,C,D) 4000 random trees (depth <= 5 binary, <= 4 ternary; kernels with exact zeros):")
    print("   max H2/sigma = %.4f   (c* = %.6f, constant of Theorem 2.1(c) = 4)" % (w['r'], CSTAR))
    print("   max |H2 - E_P sum Lam h| = %.2e ;  max of H2 - (sigma_P+sigma_Q)/2 = %.2e" % (w['ident'], w['two']))
    print("   max TV / [sigma + sqrt(sigma^2+2 sigma)] = %.4f  (new bound; must be <= 1)" % w['tv'])
    print("   max TV / sqrt(sigma) = %.4f   (file: sqrt(8) = 2.828, with c*: 2.435; new bound: <= 2)" % w['tvsqrt'])
    print("   max P(Q-density = 0)/sigma = %.4f  (new bound 2; the file's route gives 8, or 2c* = 5.93)" % w['z'])
    print("(A) L-BFGS-B from random starts, maximising H2/sigma (exact tree evaluation):")
    for (D, b, ns) in [(2, 2, 30), (3, 2, 30), (4, 2, 16), (5, 2, 8), (6, 2, 4), (3, 3, 10), (4, 3, 4)]:
        best, th = optimise(obj_ratio, D, b, ns)
        print("    depth %d, branching %d: best ratio %.5f   %s" % (D, b, best, "VIOLATION" if best > CSTAR + 1e-9 else "(< c*)"))
    print("(C) maximising TV / [sigma + sqrt(sigma^2 + 2 sigma)] over trees with sigma < 1/4:")
    for (D, b, ns) in [(1, 2, 30), (2, 2, 40), (3, 2, 30), (4, 2, 16), (5, 2, 8), (3, 3, 10)]:
        best, th = optimise(obj_tv, D, b, ns)
        H2, sP, sQ, TV, lamh, Z = stats(*unpack(th, D, b))
        print("    depth %d, branching %d: best %.6f  at sigma = %.3e, TV = %.3e   %s" % (D, b, best, sP, TV, "VIOLATION" if best > 1 + 1e-9 else ""))
    print("    the curve F(s) = sup TV at sigma <= s (depth 4 binary, penalty method), against the bounds:")
    print("      s       found TV   new bound   2 sqrt(s)   sqrt(2c* s)   sqrt(8 s)")
    for s0 in [0.001, 0.01, 0.05, 0.1, 0.2]:
        bestTV = 0.0
        for (D, b, ns) in [(1, 2, 10), (2, 2, 20), (4, 2, 10)]:
            best, th = optimise(make_obj_tv_at(s0), D, b, ns)
            H2, sP, sQ, TV, lamh, Z = stats(*unpack(th, D, b))
            if sP <= s0 * (1 + 1e-6): bestTV = max(bestTV, TV)
        print("      %-7g %.5f    %.5f     %.5f     %.5f       %.5f" % (s0, bestTV, tvbound(s0), min(1, 2 * math.sqrt(s0)),
              min(1, math.sqrt(2 * CSTAR * s0)), min(1, math.sqrt(8 * s0))))
    print("(D) maximising P(Q-density = 0)/sigma from starts with exact zeros (surrogate objective, then exact evaluation after rounding small q to 0):")
    for (D, b, ns) in [(1, 2, 20), (2, 2, 40), (3, 2, 40), (4, 2, 20), (3, 3, 16)]:
        best, th = optimise(obj_z, D, b, ns, sparse=0.4)     # start from kernels with exact zeros: the objective is flat without them
        ps, qs = unpack(th, D, b)
        qs2 = []
        for q in qs:
            q = np.where(q < 1e-7, 0.0, q); q = q / q.sum(1, keepdims=True); qs2.append(q)
        H2, sP, sQ, TV, lamh, Z = stats(ps, qs2)
        print("    depth %d, branching %d: surrogate %.5f ; exact P(Z)/sigma after rounding = %.5f  %s" % (D, b, best, Z / sP, "VIOLATION" if Z / sP > 2 + 1e-6 else ""))
    wv, wd = onestep_tv_potential()
    print("(E) potentials U_m = (m-x)_+^2/(m^2-1): max over extreme laws of E U(Lam r) - U(Lam) - c_m(1-E r) = %.3e (must be <= 0 up to rounding; the terms are of size 100 for m = 1.01);" % wv)
    print("    min over x of U_m(x) - (1-x^2)_+ = %.3e (must be >= 0)" % wd)
    q0, c, worst, arg = step2_highprec()
    print("    Theorem 2.7, Step 2 in 50-digit arithmetic at 4000 random points: q0 = %s, c* = %s" % (str(q0)[:22], str(c)[:22]))
    print("    min of [parabola - V] = %s at (Lam, a) = (%.6f, %.6f)  (must be >= 0)" % (mpstr(worst) if False else str(worst)[:12], arg[0], arg[1]))
    print("time %.0f s" % (time.time() - t0))
