#!/usr/bin/env python3
"""Exact checks of the two sharper one-sided statements proposed in the attack report
(verification/hellinger-runs-attack.md, finding M1), and of their use in Theorem R2.

Setting of Theorem 2.1 of research/prove-b/hellinger-runs.md: laws P, Q of a sequence generated by kernels
p_i, q_i; sigma := E_P sum_i H^2(p_i, q_i)(history).

 (E1) for every event G and eta > 0:   P(G) <= (1+eta) Q(G) + 2 (1 + 1/eta) sigma.
      The best event is G = {P > (1+eta) Q}; so the test is  sum_leaves (P - (1+eta) Q)_+ <= 2(1+1/eta) sigma.
      (The target file obtains (1+eta) Q(G) + (1+1/eta) * 8 sigma from H^2 <= 4 sigma, or 2c* = 5.93 in place of 8.)
 (E2) TV(P,Q) <= sigma + sqrt(sigma^2 + 2 sigma), tested only where this bound is below 1/2 (non-trivial regime).
 (E3) Protocol R, exact expectations (same evaluator as hellinger-runs_attack_r2.py):
        E sum_runs (Q_M(T) - (1+eta) Q_P)_+  <=  (1 + 1/eta) L K ln2 / n       (so: E Q_M(T)(G) <= (1+eta) Q_P(G) + (1+1/eta) L K ln2/n)
        E TV(Q_M(T), Q_P) <= s + sqrt(s^2 + 2s),  s = L K ln2/(2n),  on instances with s <= 1/8.

Run:  python3 hellinger-runs_attack_events.py        (about 3 minutes)
"""
import importlib.util, os, math, time
import numpy as np
from scipy.optimize import minimize

here = os.path.dirname(os.path.abspath(__file__))
def load(name):
    spec = importlib.util.spec_from_file_location(name.replace('-', '_'), os.path.join(here, name + '.py'))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m
T = load('hellinger-runs_attack_l4')
R = load('hellinger-runs_attack_r2')
rng = np.random.default_rng(99)
T.rng = rng; R.rng = rng
LN2 = math.log(2.0)

def leaves(ps, qs):
    P = np.ones(1); Q = np.ones(1); s = 0.0
    for p, q in zip(ps, qs):
        h = 0.5 * ((np.sqrt(p) - np.sqrt(q)) ** 2).sum(1); s += float((P * h).sum())   # = 1 - sum sqrt(pq), without cancellation
        P = (P[:, None] * p).reshape(-1); Q = (Q[:, None] * q).reshape(-1)
    return P, Q, s

def ev_ratio(th, D, b, eta):
    P, Q, s = leaves(*T.unpack(th, D, b))
    if s < 1e-12:            # sigma = 0 up to rounding: P = Q on the reachable part and both sides vanish
        return 0.0
    return float(np.maximum(P - (1 + eta) * Q, 0).sum()) / s / (2 * (1 + 1 / eta))

def tv_ratio_nontrivial(th, D, b):
    P, Q, s = leaves(*T.unpack(th, D, b))
    if s < 1e-12:
        return 0.0
    bound = s + math.sqrt(s * s + 2 * s)
    tv = 0.5 * float(np.abs(P - Q).sum())
    return tv / bound - 50.0 * max(0.0, bound - 0.5)

def opt(f, D, b, nstart, maxiter=250):
    best = -1e9
    for s in range(nstart):
        th0 = T.fix_zero_rows(T.random_theta(D, b, float(rng.choice([0.0, 0.3]))), D, b)
        res = minimize(lambda th: -f(th, D, b), th0, method='L-BFGS-B', bounds=[(-30.0, 30.0)] * th0.size, options=dict(maxiter=maxiter))
        best = max(best, -res.fun)
    return best

# ---- Protocol R with the event functional (copy of R.evaluate with two more totals)
def evaluate_events(nu, w, sc, mu0, n, etas=(0.25, 1.0, 4.0)):
    H, nx, ny = nu.shape; L = sc.L
    P = nu[0]; K = math.log2(1.0 / w[0])
    qP, dP = sc.laws(P, mu0)
    states = {tuple([0] * (nx * ny)): 1.0}; cache = {}
    tot_ev = np.zeros(len(etas)); tot_TV = 0.0
    lognu = np.log(np.maximum(nu, 1e-300)); zero = (nu <= 0)
    for t in range(1, n + 1):
        new = {}
        for D, pD in states.items():
            if D not in cache:
                c = np.array(D, dtype=float).reshape(nx, ny)
                ll = (c[None] * lognu).sum((1, 2)); ll[(zero & (c[None] > 0)).any((1, 2))] = -np.inf
                post = w * np.exp(ll - ll.max()); post = post / post.sum()
                M = (post[:, None, None] * nu).sum(0)
                qM, dM = sc.laws(M, mu0)
                ev = np.array([float(np.maximum(qM - (1 + e) * qP, 0).sum()) for e in etas])
                cache[D] = (ev, 0.5 * float(np.abs(qM - qP).sum()), dM)
            ev, TV, dM = cache[D]
            tot_ev += pD * ev; tot_TV += pD * TV
            stay = pD
            for x in range(nx):
                if dM[x] <= 0: continue
                for y in range(ny):
                    pr = pD * dM[x] * P[x, y] / L
                    if pr <= 0: continue
                    D2 = list(D); D2[x * ny + y] += 1; D2 = tuple(D2)
                    new[D2] = new.get(D2, 0.0) + pr; stay -= pr
            if stay > 1e-15: new[D] = new.get(D, 0.0) + stay
        states = new
    LK = L * K * LN2; s = LK / (2 * n)
    r_ev = (tot_ev / n) / np.array([(1 + 1 / e) * LK / n for e in etas])
    r_tv = (tot_TV / n) / (s + math.sqrt(s * s + 2 * s))
    return r_ev, r_tv, s

if __name__ == '__main__':
    t0 = time.time()
    print("(E1) P(G) <= (1+eta) Q(G) + 2(1+1/eta) sigma : largest value of [sum (P-(1+eta)Q)_+] / [2(1+1/eta) sigma]  (must be <= 1)")
    for eta in [0.25, 1.0, 4.0, 100.0]:
        w = 0.0
        for rep in range(3000):
            D = int(rng.integers(1, 6)); b = int(rng.integers(2, 4)); D = min(D, 4) if b == 3 else D
            th = T.fix_zero_rows(T.random_theta(D, b, float(rng.choice([0.0, 0.2, 0.5]))), D, b)
            w = max(w, ev_ratio(th, D, b, eta))
        o = max(opt(lambda th, D, b: ev_ratio(th, D, b, eta), D, b, ns) for (D, b, ns) in [(1, 2, 20), (2, 2, 30), (3, 2, 20), (4, 2, 12), (2, 3, 12)])
        print("     eta = %-6g random trees: %.5f   optimised: %.8f  %s (the file's constant corresponds to 4.0000 here, 2.9641 with c*)" % (eta, w, o, "VIOLATION" if max(w, o) > 1 + 1e-7 else ""))
    print("(E2) TV <= sigma + sqrt(sigma^2+2 sigma), optimised over trees with bound <= 1/2: largest TV/bound")
    for (D, b, ns) in [(1, 2, 20), (2, 2, 30), (3, 2, 30), (4, 2, 16), (5, 2, 8), (3, 3, 10)]:
        v = opt(tv_ratio_nontrivial, D, b, ns)
        print("     depth %d, branching %d: %.8f  %s" % (D, b, v, "VIOLATION" if v > 1 + 1e-7 else ""))
    print("(E3) Protocol R, exact: largest ratios over random instances (n <= 6) and hill climbing")
    top_ev = np.zeros(3); top_tv = 0.0; cnt = 0
    for rep in range(1500):
        kind = rng.choice(['adaptive', 'adaptive', 'fixed', 'same']); n = int(rng.integers(1, 7))
        nu, w, sc, mu0 = R.random_instance(kind)
        r_ev, r_tv, s = evaluate_events(nu, w, sc, mu0, n); cnt += 1
        top_ev = np.maximum(top_ev, r_ev)
        if s <= 0.125: top_tv = max(top_tv, r_tv)
    # hill climbing on the eta = 1 event ratio and on the TV ratio (s <= 1/8)
    for target in ['ev', 'tv']:
        for start in range(12):
            kind = ['adaptive', 'adaptive', 'fixed', 'same'][start % 4]; n = [2, 3, 4, 6][start % 4]
            nu, w, sc, mu0 = R.random_instance(kind)
            def score(nu, w, mu0):
                r_ev, r_tv, s = evaluate_events(nu, w, sc, mu0, n)
                return (r_ev, r_tv, s, (r_ev[1] if target == 'ev' else (r_tv if s <= 0.125 else -s)))
            cur = score(nu, w, mu0)
            for it in range(120):
                nu2, w2, m2 = R.perturb(nu, w, mu0, scale=0.3 * (1 - it / 120) + 0.02)
                c2 = score(nu2, w2, m2)
                if c2[3] > cur[3]: cur, nu, w, mu0 = c2, nu2, w2, m2
            top_ev = np.maximum(top_ev, cur[0])
            if cur[2] <= 0.125: top_tv = max(top_tv, cur[1])
    print("     events: eta = 0.25: %.5f   eta = 1: %.5f   eta = 4: %.5f   (each must be <= 1)" % tuple(top_ev))
    print("     TV against s + sqrt(s^2+2s), instances with s <= 1/8: %.5f   (must be <= 1)" % top_tv)
    print("time %.0f s" % (time.time() - t0))
