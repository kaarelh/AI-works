"""Analysis of the composition test (see PREDICTIONS.md, written before the network runs were inspected).

Reads <scratchpad>/results_comp/{fixed,online}_adam_comp*.npz (written by run_comp.sh) and race_predictions.json.
For each target: the networks' final test-set Fourier coefficient on x1x2x3x4 against n; n*_4 (coefficient >= 0.4 = 80%
of its target 0.5, log-interpolated); the training step at which the coefficient first reaches 0.4 at each n; the
same for the pairs; and in the online protocol the number of fresh samples until the coefficient reaches 0.4.
Writes composition/RESULTS.md, composition/results.json and figures/composition.png.
"""
import os, json, numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
R = "/tmp/claude-0/-home-user-AI-works/addd33f6-5c52-5bee-997e-3f98d4e90609/scratchpad/results_comp"
FNS = ["compA", "compB", "compC", "compD", "compE", "compF", "compL", "compG", "compH"]
DESC = {"compA": "s + x1x2 + x3x4 + x1x2x3x4", "compB": "s + x1x2x3x4", "compC": "s + x1x2 + x2x3 + x1x2x3x4",
        "compD": "s + x1x2 + x3x4", "compE": "x1x2 + x3x4 + x1x2x3x4", "compF": "x1x2x3x4", "compL": "s",
        "compG": "s + x5x6 + x7x8 + x1x2x3x4", "compH": "s + x1x2 + x1x2x3x4"}
R60 = R + "_d60"
THR = 0.4
COL = dict(compA="#1f77b4", compB="#ff7f0e", compC="#2ca02c", compE="#d62728", compF="#9467bd", compG="#8c564b", compH="#e377c2")


def interp_cross(xs, ys, thr=THR):
    for i in range(len(xs)):
        if ys[i] >= thr:
            if i == 0:
                return float(xs[0])
            f = (thr - ys[i - 1]) / (ys[i] - ys[i - 1])
            return float(np.exp(np.log(xs[i - 1]) + f * (np.log(xs[i]) - np.log(xs[i - 1]))))
    return float("inf")


def load_fixed(fn, root=None):
    z = np.load(os.path.join(root or R, f"fixed_adam_{fn}.npz"))
    sets = [tuple(s) for s in json.loads(str(z["sets"]))]
    ns = list(z["ns"]); seeds = sorted(set(int(s) for s in z["net_s"]))
    I = {(int(n), int(s)): j for j, (n, s) in enumerate(zip(z["net_n"], z["net_s"]))}
    coef = z["coef"]                                   # [ckpt, net, set]
    def C(S):
        j = sets.index(S)
        return np.array([[coef[:, I[(int(n), s)], j] for s in seeds] for n in ns])   # [n, seed, ckpt]
    tl = np.array([[z["test_loss"][:, I[(int(n), s)]] for s in seeds] for n in ns])
    return dict(ns=np.array(ns), steps=np.array(z["step"]), C=C, test_loss=tl)


def first_step(steps, curve, thr=THR):
    hit = np.where(curve >= thr)[0]
    return int(steps[hit[0]]) if len(hit) else None


def main():
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    race = json.load(open(os.path.join(HERE, "race_predictions.json")))
    race["res"].update(json.load(open(os.path.join(HERE, "race_predictions_GH.json")))["res"])
    race60 = json.load(open(os.path.join(HERE, "race_predictions_d60.json")))
    out, L = {}, ["# Composition test: results (generated by composition/analyze.py)", "",
                  "Predictions were recorded first, in [PREDICTIONS.md](PREDICTIONS.md). Networks: the study's μP MLP (width 128), Adam with "
                  "learning rate 1e-3, minibatch 64, 20000 steps, d = 30, 3 seeds; square loss on the real-valued targets. "
                  "'coef' = test-set Fourier coefficient of the network output (target value 0.5 for every term).", "",
                  "## Sample complexity of the degree-4 term (fixed training set)", "",
                  "| target | n*_4 networks | n*_4 race (predicted) | x1x2x3x4 coefficient at n = 256 / 512 / 1024 / 2048 / 4096 (seed mean) |",
                  "|---|---|---|---|"]
    fig, axs = plt.subplots(1, 3, figsize=(14, 3.8))
    for fn in FNS:
        if not os.path.exists(os.path.join(R, f"fixed_adam_{fn}.npz")):
            continue
        F = load_fixed(fn); c4 = F["C"]((0, 1, 2, 3))      # [n, seed, ckpt]
        final = c4[:, :, -1].mean(1)
        nstar = interp_cross(F["ns"], final)
        rn = interp_cross(np.array(race["ns"]), np.array(race["res"][fn]["p1234"]).mean(1))
        pick = [list(F["ns"]).index(n) for n in (256, 512, 1024, 2048, 4096)]
        out[fn] = dict(nstar4=nstar, race_nstar4=rn, final_c4=final.tolist(), ns=F["ns"].tolist(),
                       steps=F["steps"].tolist(), c4_curve=c4.mean(1).tolist())
        f = lambda v: "never" if not np.isfinite(v) else f"{v:.0f}"
        L.append(f"| {fn}: {DESC[fn]} | {f(nstar)} | {f(rn)} | " + " / ".join(f"{final[i]:.2f}" for i in pick) + " |")
        if fn != "compD" and fn != "compL":
            axs[0].semilogx(F["ns"], final, "o-", ms=3, color=COL[fn], label=f"{fn}: {DESC[fn]}")
    axs[0].axhline(THR, color="gray", lw=0.6, ls="--"); axs[0].set_xlabel("training-set size n")
    axs[0].set_ylabel("x1x2x3x4 coefficient at step 20000"); axs[0].legend(fontsize=6); axs[0].set_title("d = 30", fontsize=9)

    L += ["", "## Time to learn each term at large n (fixed training set, steps until the coefficient first reaches 0.4; seed mean of the curves)", "",
          "| target | n | x1 | x1x2 | x3x4 | x2x3 | x1x2x3x4 |", "|---|---|---|---|---|---|---|"]
    for fn in FNS:
        if fn not in out:
            continue
        F = load_fixed(fn)
        for n in (2048, 16384):
            a = list(F["ns"]).index(n); cells = []
            for S in [(0,), (0, 1), (2, 3), (1, 2), (0, 1, 2, 3)]:
                cur = F["C"](S)[a].mean(0)
                v = first_step(F["steps"], cur) if np.max(np.abs(cur)) > 0 else None
                cells.append("–" if v is None else str(v))
            L.append(f"| {fn} | {n} | " + " | ".join(cells) + " |")
    L += ["", "## d = 60 (2 seeds; race predictions recorded before these runs)", "",
          "| target | n*_4 networks d=30 | n*_4 networks d=60 | ratio 60/30 | race d=60 (predicted) | coefficient at n = 1024 / 2048 / 4096 / 8192 / 16384 / 32768 |",
          "|---|---|---|---|---|---|"]
    for fn in ["compA", "compB", "compC", "compF"]:
        if not os.path.exists(os.path.join(R60, f"fixed_adam_{fn}.npz")):
            continue
        F = load_fixed(fn, R60); c4 = F["C"]((0, 1, 2, 3)); final = c4[:, :, -1].mean(1)
        n60 = interp_cross(F["ns"], final); n30 = out[fn]["nstar4"]
        r60 = interp_cross(np.array(race60["ns"]), np.array(race60["res"][fn]["p1234"]).mean(1))
        pick = [list(F["ns"]).index(n) for n in (1024, 2048, 4096, 8192, 16384, 32768)]
        axs[1].semilogx(F["ns"], final, "o-", ms=3, color=COL[fn], label=f"{fn}: {DESC[fn]}")
        out[fn]["nstar4_d60"] = n60; out[fn]["race_nstar4_d60"] = r60; out[fn]["final_c4_d60"] = final.tolist()
        f = lambda v: "never" if not np.isfinite(v) else f"{v:.0f}"
        L.append(f"| {fn}: {DESC[fn]} | {f(n30)} | {f(n60)} | {n60 / n30:.2f} | {f(r60)} | " + " / ".join(f"{final[i]:.2f}" for i in pick) + " |")
    axs[1].axhline(THR, color="gray", lw=0.6, ls="--"); axs[1].set_xlabel("training-set size n"); axs[1].set_title("d = 60", fontsize=9); axs[1].legend(fontsize=6)
    L += ["", "## Online protocol (fresh minibatch of 64 every step): samples until the x1x2x3x4 coefficient reaches 0.4", "",
          "| target | samples (per seed) | median |", "|---|---|---|"]
    for fn in FNS:
        p = os.path.join(R, f"online_adam_{fn}.npz")
        if not os.path.exists(p):
            continue
        z = np.load(p); sets = [tuple(s) for s in json.loads(str(z["sets"]))]; j = sets.index((0, 1, 2, 3))
        steps = np.array(z["step"]); c = z["coef"][:, :, j]          # [ckpt, seed, set] -> [ckpt, seed]
        per = [first_step(steps, c[:, s]) for s in range(c.shape[1])]
        sam = [None if v is None else 64 * v for v in per]
        med = np.median([v for v in sam if v is not None]) if any(v is not None for v in sam) else None
        out.setdefault(fn, {})["online_samples"] = sam
        L.append(f"| {fn}: {DESC[fn]} | " + ", ".join("never" if v is None else str(v) for v in sam) + f" | {'never' if med is None else int(med)} |")
        axs[2].semilogx(np.maximum(steps, 1) * 64, c.mean(1), color=COL[fn], label=fn)
    axs[2].axhline(THR, color="gray", lw=0.6, ls="--"); axs[2].set_xlabel("fresh samples seen (online, d = 30)")
    axs[2].set_ylabel("x1x2x3x4 coefficient"); axs[2].legend(fontsize=6)
    fig.tight_layout(); fig.savefig(os.path.join(os.path.dirname(HERE), "figures", "composition.png"), dpi=130)
    json.dump(out, open(os.path.join(HERE, "results.json"), "w"), indent=1)
    open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
