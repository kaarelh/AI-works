"""A lean test of the 'kernel background + grown features' hypothesis (a quick version of the workflow's hybrid task).

Hybrid score: f = f_race / sd_S(f_race) + gamma * f_nngp / sd_S(f_nngp), where f_race is the race model's real-valued readout
(calibrated setting, unchanged) and f_nngp the NNGP-kernel ridge regression score (n <= 4096; above that the hybrid is the race
alone).  gamma = 0 is the race model.  Scores every gamma against the networks.  Writes study/HYBRID-QUICK.md.
"""
import os, sys, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C
from models.race import Race
from models.baselines import nngp_table
from scipy.linalg import cho_factor, cho_solve

GAMMAS = [0.0, 0.25, 0.5, 1.0, 2.0]
HERE = os.path.dirname(os.path.abspath(__file__))


def race_scores(fit, Z):
    cl = {k: c.cell_contents for k, c in zip(fit["predict"].__code__.co_freevars, fit["predict"].__closure__)}
    G, a, c0, relu, d = cl["G_"], cl["a_"], cl["c_"], cl["relu"], cl["d"]
    Z = np.asarray(Z, dtype=np.float32)
    W = np.zeros((len(Z), d + len(G)), dtype=np.float32); W[:, :d] = Z; Dz = d
    out = np.full(len(Z), c0)
    for j, (gw, gb, gwire, gsd, gmu) in enumerate(G):
        sz = np.rint(W[:, :len(gw)] @ gw.astype(np.float32)).astype(np.float64)
        ind = (sz > gb).astype(np.float64)
        gv = np.maximum(sz - gb, 0.0) if relu else ind
        if gwire is not None:
            W[:, Dz] = 2 * ind - 1; Dz += 1
        out += a[j] * (gv - gmu) / gsd
    return out


def nngp_scores(X, y, Z, ridge=1e-4):
    d = X.shape[1]; table = nngp_table(d)
    gram = lambda A, B: table[((A @ B.T).astype(np.int64) + d) // 2].astype(np.float64)
    K = gram(X, X); lam = ridge * np.trace(K) / len(X)
    c = cho_solve(cho_factor(K + lam * np.eye(len(X))), y.astype(np.float64))
    return gram(Z, X) @ c, K @ c


def main():
    res = {g: dict(model=f"hybrid-g{g}", fns=C.FNS, ns=C.NS, seeds=C.SEEDS, test_err={}, train_err={}, time={}, size={},
                   fit_seconds={}, pred={}) for g in GAMMAS}
    M = Race(theta=1.5, Q=3, gate="relu")
    for fn in C.FNS:
        Xte, yte = C.test_data(fn)
        for g in GAMMAS:
            for k in ("test_err", "train_err", "time", "size", "fit_seconds"):
                res[g][k][fn] = np.zeros((len(C.NS), len(C.SEEDS)))
            res[g]["pred"][fn] = np.zeros((len(C.NS), len(C.SEEDS), len(yte)), dtype=np.int8)
        for a_, n in enumerate(C.NS):
            for b_, s in enumerate(C.SEEDS):
                X, y = C.train_data(fn, s, n)
                fit = M.fit(X, y, np.random.default_rng([s, n, C._fn_seed(fn)]))
                fr_te, fr_tr = race_scores(fit, Xte), race_scores(fit, X)
                if n <= 4096:
                    fk_te, fk_tr = nngp_scores(X, y, Xte)
                else:
                    fk_te, fk_tr = np.zeros(len(Xte)), np.zeros(n)
                sr = max(fr_tr.std(), 1e-9); sk = max(fk_tr.std(), 1e-9)
                for g in GAMMAS:
                    p_te = np.where(fr_te / sr + g * fk_te / sk > 0, 1, -1)
                    p_tr = np.where(fr_tr / sr + g * fk_tr / sk > 0, 1, -1)
                    res[g]["pred"][fn][a_, b_] = p_te; res[g]["test_err"][fn][a_, b_] = np.mean(p_te != yte)
                    res[g]["train_err"][fn][a_, b_] = np.mean(p_tr != y); res[g]["time"][fn][a_, b_] = fit["time"]
        print(fn, " ".join(f"g{g}:{res[g]['test_err'][fn].mean():.3f}" for g in GAMMAS), flush=True)
    L = ["# Race + kernel background, quick test (generated by hybrid_quick.py)", "",
         "gamma = weight of the standardized NNGP-kernel score added to the standardized race score (gamma = 0: the race model). "
         "Same metrics as MODEL-SCOREBOARD.md; reference NN-SGD vs NN-Adam on HELDOUT: per-example agreement 0.71.", "",
         "| gamma | split | mean abs log2 n* ratio | n* Spearman | success agreement | curve MAE | per-example agreement | time Spearman |",
         "|---|---|---|---|---|---|---|---|"]
    for g in GAMMAS:
        for split, fns in (("HELDOUT", C.HELDOUT), ("CALIB", C.CALIB)):
            b = C.compare(res[g], "adam", fns=fns, verbose=False)
            L.append(f"| {g} | {split} | {b['sc_mean_abs_log2_ratio']:.2f} | {b['sc_spearman']:.2f} | {b['success_agreement']:.2f} | "
                     f"{b['curve_mae']:.3f} | {b['example_agreement_score']:.2f} | {b['time_spearman']:.2f} |")
    open(os.path.join(HERE, "HYBRID-QUICK.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
