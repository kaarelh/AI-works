    fig.legend(handles=hs, loc="lower center", ncol=7, frameon=False, fontsize=7, bbox_to_anchor=(0.5, -0.005))
    fig.tight_layout(rect=(0, 0.035, 1, 1))
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(A.FIG, f"fig_order.{ext}"), dpi=200)
    plt.close(fig)


