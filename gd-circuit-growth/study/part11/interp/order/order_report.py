"""Part 11, Q7 'order': tables and the figure from order/results/order_summary.json (order_analysis.py) and the cells.

Writes
  tables/order_targets.md     one row per target: DFG rounds used at Part 5's n, Kendall tau-b on each axis, pairs
  tables/order_chars.md|csv   one row per target character: yhat, degree, network onsets (time; n), DFG n onsets per
                              seed and how chi_S entered at the median seed's onset n, round-0 detectability n_glob
  tables/order_checks.md      Part 5's qualitative findings, checked for DFG
  tables/order_numbers.json   every number quoted in ORDER.md
  figures/fig_order.pdf|png   per target: x = network onset step (online, seed-mean phi), y = the n from which the
                              character is in the final model (filled: DFG, median of 3 seeds; open: networks, |S| <= 4)
"""
import os, sys, json, gzip, math, itertools, numpy as np
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import order_analysis as A                                                      # noqa: E402

INF = float("inf")


def F(v):
    if v is None:
        return None
    if isinstance(v, str):
        return INF if v == "inf" else -INF if v == "-inf" else v
    return v


def fnum(v, nd=2):
    v = F(v)
    if v is None:
        return "–"
    if isinstance(v, float) and not np.isfinite(v):
        return "never"
    if isinstance(v, (int, np.integer)) or (isinstance(v, float) and abs(v - round(v)) < 1e-9 and abs(v) >= 10):
        return f"{int(round(v))}"
    return f"{v:.{nd}f}"


def tfmt(t):
    return "all tied" if t is None else f"{t:+.2f}"


def load():
    return json.load(open(os.path.join(A.RES, "order_summary.json")))


def med3(vals):
    v = [F(x) for x in vals]
    if any(x is None for x in v):
        return None
    return A.med(v)


def char_rows(S):
    rows = []
    for fn, T in S["targets"].items():
        for ch in T["chars"]:
            nt = T["net_time"]; nn = T["net_n"] or {}
            dn = [F(T["dfg_n"][str(s)][ch]["n"]) for s in A.SEEDS]
            # how chi_S was in the final model at the median seed's onset n (explicit admission class, or a block)
            m = A.med(dn) if None not in dn else None
            how = []
            for s in A.SEEDS:
                n0 = dn[s]
                if n0 is None or not np.isfinite(n0):
                    how.append("never"); continue
                c = A.load_cell(fn, int(n0), s); e = c["explicit"].get(ch)
                if e is not None:
                    how.append(e["how"] if e["how"] != "test" else (e["cls"] or "test"))
                else:
                    how.append("block")
            rows.append(dict(target=fn, char=ch, deg=T["deg"][ch], yhat=T["yhat"][ch],
                             net_online=F(nt["online"][ch]["mean"]), net_16384=F(nt["16384"][ch]["mean"]),
                             net_2048=F(nt["2048"][ch]["mean"]), net_512=F(nt["512"][ch]["mean"]),
                             net_final_2048=nt["2048"][ch]["final_mean"], net_final_512=nt["512"][ch]["final_mean"],
                             net_n=None if ch not in nn else med3(nn[ch]["seeds"]),
                             net_n_seeds=None if ch not in nn else [F(x) for x in nn[ch]["seeds"]],
                             dfg_n=m, dfg_n_seeds=dn, dfg_how=how, nglob=F(T["nglob"][ch])))
    return rows


def main():
    S = load(); NUM = {}
    rows = char_rows(S)
    # ------------------------------------------------------------------ per-character table (csv + md)
    import csv
    with open(os.path.join(A.TAB, "order_chars.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["target", "char", "deg", "yhat", "net_onset_online", "net_onset_16384", "net_onset_2048", "net_onset_512",
                    "net_phi_end_2048", "net_phi_end_512", "net_n_onset_median", "net_n_onset_seeds", "dfg_n_onset_median",
                    "dfg_n_onset_seeds", "dfg_how_at_onset_seeds", "n_glob"])
        for r in rows:
            w.writerow([r["target"], r["char"], r["deg"], r["yhat"], fnum(r["net_online"], 0), fnum(r["net_16384"], 0),
                        fnum(r["net_2048"], 0), fnum(r["net_512"], 0), f"{r['net_final_2048']:.2f}", f"{r['net_final_512']:.2f}",
                        fnum(r["net_n"]), "/".join(fnum(x) for x in (r["net_n_seeds"] or [])), fnum(r["dfg_n"]),
                        "/".join(fnum(x) for x in r["dfg_n_seeds"]), "/".join(r["dfg_how"]), fnum(r["nglob"], 0)])
    # md: small targets character by character, big ones (rmaj9, dlist5, dnf3) grouped by (degree, |yhat|)
    L = ["# DFG alone vs the Part 5 networks: per-character order (generated by order_report.py)", "",
         "Columns: yhat = Fourier coefficient; network onset = first step with learned fraction >= 1/2 for good, from the "
         "seed-mean learned fraction (Part 5, trajectories/results); network n = smallest n of the fixed-n study whose "
         "network at step 20000 has learned fraction >= 1/2 (for good over larger n), median of 3 seeds (|S| <= 4 only); "
         "DFG n = the same for DFG's final least-squares function (per seed s0/s1/s2, and how chi_S was carried at that "
         "n: its admission class, 'linear-block', 'forced', or 'block' when only a sum block carried it); n_glob = the "
         "round-0 global-class detection size 2 ln(4 K C(30,|S|)/delta)(1 - yhat_0^2)/yhat_S^2 (degree <= 4).", ""]
    big = {"rmaj9", "dlist5", "dnf3"}
    for fn in A.TARGETS:
        R = [r for r in rows if r["target"] == fn]
        L += [f"## {fn}", ""]
        L.append("| char | deg | yhat | net onset online / 16384 / 2048 / 512 (steps) | net phi at end, 2048 / 512 | net n (median) | DFG n s0/s1/s2 | DFG: how | n_glob |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        if fn not in big:
            for r in sorted(R, key=lambda r: (F(r["net_online"]) if np.isfinite(F(r["net_online"])) else 1e9, r["char"])):
                L.append(f"| {r['char']} | {r['deg']} | {r['yhat']:+.3f} | {fnum(r['net_online'],0)} / {fnum(r['net_16384'],0)} / "
                         f"{fnum(r['net_2048'],0)} / {fnum(r['net_512'],0)} | {r['net_final_2048']:.2f} / {r['net_final_512']:.2f} | "
                         f"{fnum(r['net_n'])} | {'/'.join(fnum(x) for x in r['dfg_n_seeds'])} | {'/'.join(r['dfg_how'])} | {fnum(r['nglob'],0)} |")
        else:
            G = defaultdict(list)
            for r in R:
                G[(r["deg"], round(abs(r["yhat"]), 4))].append(r)
            for (dg, ay), rr in sorted(G.items()):
                def rng(key, nd=0):
                    v = [F(r[key]) for r in rr if F(r[key]) is not None]
                    if not v:
                        return "–"
                    fin = [x for x in v if np.isfinite(x)]
                    nev = len(v) - len(fin)
                    s = (f"{fnum(min(fin), nd)}–{fnum(max(fin), nd)}" if fin and min(fin) != max(fin) else fnum(fin[0], nd) if fin else "")
                    return (s + (f" (+{nev} never)" if nev and fin else "never" if nev else "")).strip()
                dn = Counter("/".join(fnum(x) for x in r["dfg_n_seeds"]) for r in rr).most_common(3)
                hw = Counter(h for r in rr for h in r["dfg_how"]).most_common(3)
                L.append(f"| {len(rr)} chars, e.g. {rr[0]['char']} | {dg} | ±{ay:.4f} | {rng('net_online')} / {rng('net_16384')} / "
                         f"{rng('net_2048')} / {rng('net_512')} | {rng('net_final_2048', 2)} / {rng('net_final_512', 2)} | {rng('net_n')} | "
                         f"{'; '.join(f'{k} ({v})' for k, v in dn)} | {'; '.join(f'{k} {v}' for k, v in hw)} | {rng('nglob')} |")
        L.append("")
    open(os.path.join(A.TAB, "order_chars.md"), "w").write("\n".join(L) + "\n")

    # ------------------------------------------------------------------ per-target table
    L = ["# DFG alone vs the Part 5 networks: order per target (generated by order_report.py)", "",
         "tau = Kendall tau-b over the target's characters ('never' tied last; 'all tied' = one order has a single rank). "
         "Positive = same order.  Axes: network time = onset step of the seed-mean learned fraction, online; DFG z0 = "
         "priority inside DFG's first round (descending round-0 z-score of the character's best test); DFG n / network n = "
         "the smallest n from which the final model carries the character (median of 3 seeds; network n only for |S| <= 4, "
         "the fixed-n study's recorded characters). Pairs (network time vs DFG n): ordered by the networks (onsets more "
         "than 1.35x apart) and concordant / tied / inverted in DFG's n order.", "",
         "| target | chars | DFG rounds used, n = 512 / 2048 / 16384 (s0,s1,s2) | tau(net time, DFG z0 @16384) | tau(net time, DFG n) | pairs c/t/i | tau(net n, DFG n), |S|<=4 | tau(net time, net n) |",
         "|---|---|---|---|---|---|---|---|"]
    NUM["targets"] = {}
    for fn in A.TARGETS:
        T = S["targets"][fn]; C = T["cmp"]
        ru = " / ".join(",".join(str(T["dfg"][str(n)][str(s)]["nrounds"]) for s in A.SEEDS) for n in (512, 2048, 16384))
        z16 = [p["tau_z0"] for p in C["16384"]["per_seed"]]
        z16m = np.mean([t for t in z16 if t is not None]) if any(t is not None for t in z16) else None
        pn = C["online"]["pairs_n"]
        na = C.get("n_axis") or {}
        L.append(f"| {fn} | {len(T['chars'])} | {ru} | {tfmt(z16m)} (seeds {', '.join(tfmt(t) for t in z16)}) | {tfmt(C['online']['tau_n'])} | "
                 f"{pn['concordant']}/{pn['tied']}/{pn['inverted']} | {tfmt(na.get('tau'))} ({len(na.get('chars', []))} chars) | {tfmt(na.get('net_time_vs_net_n'))} |")
        NUM["targets"][fn] = dict(rounds=ru, tau_z0_16384=z16, tau_net_time_dfg_n=C["online"]["tau_n"], pairs_n=pn,
                                  tau_n_axis=na.get("tau"), n_axis_chars=len(na.get("chars", [])),
                                  tau_net_time_net_n=na.get("net_time_vs_net_n"),
                                  tau_nglob_dfg_n=C.get("nglob_vs_dfg_n"), tau_nglob_net_online=C.get("nglob_vs_net_online"))
    open(os.path.join(A.TAB, "order_targets.md"), "w").write("\n".join(L) + "\n")

    # ------------------------------------------------------------------ rounds used across the grid; round orders at small n
    G = {}
    for fn in A.TARGETS:
        T = S["targets"][fn]
        for n in A.NS:
            for e in T["dfg_grid"].get(str(n), []):
                G.setdefault(n, []).append((fn, e))
    NUM["rounds_by_n"] = {n: dict(cells=len(v), one_round=sum(1 for _, e in v if e["distinct_rounds"] <= 1),
                                  mean_distinct=float(np.mean([e["distinct_rounds"] for _, e in v])),
                                  max_rounds=max(e["nrounds"] for _, e in v),
                                  tau_half=[e["tau_half"] for _, e in v]) for n, v in sorted(G.items())}
    json.dump(A.clean(NUM), open(os.path.join(A.TAB, "order_numbers.json"), "w"), indent=1)
    return S, rows, NUM


if __name__ == "__main__":
    S, rows, NUM = main()
    print(open(os.path.join(A.TAB, "order_targets.md")).read())
    for n, v in NUM["rounds_by_n"].items():
        print(n, {k: vv for k, vv in v.items() if k != "tau_half"})
