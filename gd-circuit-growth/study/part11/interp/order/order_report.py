def endpoints(S, NUM):
    """At Part 5's n: the share of a target's characters whose final learned fraction is >= 1/2 ('learned') and in
    [0.25, 0.75) ('partial'), for the networks (step 20000 of each seed, Part 5 trajectories) and for DFG (final
    least-squares function of the same seed); mean over the 33 target-seed cells (targets weighted equally)."""
    E = {}
    for n in (512, 2048, 16384):
        rows = []
        for fn in A.TARGETS:
            T = S["targets"][fn]; chars = T["chars"]
            r = json.load(open(os.path.join(A.TRAJ, f"{fn}_fixed.json")))
            for s in A.SEEDS:
                ph = np.array([r["nets"][f"{n}/s{s}"]["phi"][ch][-1] for ch in chars])
                pd = np.array([T["dfg"][str(n)][str(s)]["rounds"][ch]["phi_final_ls"] for ch in chars])
                rows.append(dict(target=fn, seed=s, net_learned=float(np.mean(ph >= 0.5)), dfg_learned=float(np.mean(pd >= 0.5)),
                                 net_partial=float(np.mean((ph >= 0.25) & (ph < 0.75))),
                                 dfg_partial=float(np.mean((pd >= 0.25) & (pd < 0.75)))))
        E[n] = dict(cells=len(rows), **{k: float(np.mean([x[k] for x in rows])) for k in
                                        ("net_learned", "dfg_learned", "net_partial", "dfg_partial")},
                    per_target={fn: {k: float(np.mean([x[k] for x in rows if x["target"] == fn])) for k in
                                     ("net_learned", "dfg_learned", "net_partial", "dfg_partial")} for fn in A.TARGETS})
    NUM["endpoints"] = E
    return E


def data_cost(rows, NUM):
    """Like for like on the n axis (|S| <= 4, both learners' n onset known): DFG's median n onset against the
    networks', per character; by coefficient size (|yhat| >= 0.25 or below) and per target."""
    out = dict(all=Counter(), big=Counter(), small=Counter(), log2=[], log2_big=[], log2_small=[], per_target={})
    for r in rows:
        a, b = r["dfg_n"], r["net_n"]
        if a is None or b is None:
            continue
        k = "dfg_less" if a < b else "equal" if a == b else "dfg_more"
        grp = "big" if abs(r["yhat"]) >= 0.25 - 1e-9 else "small"
        out["all"][k] += 1; out[grp][k] += 1
        out["per_target"].setdefault(r["target"], Counter())[k] += 1
        if np.isfinite(a) and np.isfinite(b):
            v = math.log2(a / b); out["log2"].append(v); out["log2_" + grp].append(v)
    for k in ("log2", "log2_big", "log2_small"):
        v = out[k]; out[k] = dict(count=len(v), median=float(np.median(v)) if v else None, mean=float(np.mean(v)) if v else None)
    for k in ("all", "big", "small"):
        out[k] = dict(out[k])
    out["per_target"] = {t: dict(c) for t, c in out["per_target"].items()}
    NUM["data_cost"] = out
    return out


def degree_vs_size(S, rows, NUM):
    """Part 5's 'order follows construction, not coefficient size', tested on both learners: per target, Kendall tau-b
    of each order against the character's degree and against 1/|yhat| (positive = higher degree / smaller coefficient
    comes later).  Orders: networks' onset step online; networks' n onset (|S| <= 4); DFG's n onset (median seed)."""
    out = {}
    for fn in A.TARGETS:
        R = [r for r in rows if r["target"] == fn]
        deg = [r["deg"] for r in R]; inv = [1.0 / abs(r["yhat"]) for r in R]
        on = [r["net_online"] for r in R]; dn = [r["dfg_n"] for r in R]
        R4 = [r for r in R if r["net_n"] is not None]
        out[fn] = dict(net_time_deg=A.tau(deg, on), net_time_size=A.tau(inv, on), dfg_n_deg=A.tau(deg, dn),
                       dfg_n_size=A.tau(inv, dn),
                       net_n_deg=A.tau([r["deg"] for r in R4], [r["net_n"] for r in R4]) if R4 else None,
                       net_n_size=A.tau([1.0 / abs(r["yhat"]) for r in R4], [r["net_n"] for r in R4]) if R4 else None,
                       dfg_n_deg_4=A.tau([r["deg"] for r in R4], [r["dfg_n"] for r in R4]) if R4 else None,
                       dfg_n_size_4=A.tau([1.0 / abs(r["yhat"]) for r in R4], [r["dfg_n"] for r in R4]) if R4 else None)
    NUM["degree_vs_size"] = out
    L = ["# Degree or coefficient size: what each order follows (generated by order_report.py)", "",
         "Kendall tau-b per target of each order against the character's degree and against 1/|yhat|; positive = higher "
         "degree (smaller coefficient) comes later; 'all tied' = one of the two has a single value (e.g. every |yhat| "
         "equal). Orders: networks' onset step (online, seed-mean learned fraction); DFG's n onset (median of 3 seeds); "
         "on |S| <= 4 also the networks' n onset (fixed-n study) and DFG's n onset restricted to the same characters.", "",
         "| target | net time vs degree | net time vs 1/|yhat| | DFG n vs degree | DFG n vs 1/|yhat| | net n vs degree (|S|<=4) | net n vs 1/|yhat| | DFG n vs degree (|S|<=4) | DFG n vs 1/|yhat| (|S|<=4) |",
         "|---|---|---|---|---|---|---|---|---|"]
    for fn in A.TARGETS:
        o = out[fn]
        L.append(f"| {fn} | {tfmt(o['net_time_deg'])} | {tfmt(o['net_time_size'])} | {tfmt(o['dfg_n_deg'])} | {tfmt(o['dfg_n_size'])} | "
                 f"{tfmt(o['net_n_deg'])} | {tfmt(o['net_n_size'])} | {tfmt(o['dfg_n_deg_4'])} | {tfmt(o['dfg_n_size_4'])} |")
    open(os.path.join(A.TAB, "order_degree_size.md"), "w").write("\n".join(L) + "\n")
    return out


