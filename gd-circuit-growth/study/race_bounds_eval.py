"""Occam bounds for the matched discrete model itself (the race model at its calibrated setting).

For each fitted race predictor h = sign(c + sum_t a_t (g_t - mu_t)/sd_t) we bound its test error from its training error and
its own circuit, with probability >= 1 - delta simultaneously over all circuits, using a prefix-free code (Occam with a prior,
the weighted form of theory/A-discrete-model.md, Theorem A1):

    kl(train_err || test_err) <= ( ln 1/P(circuit) + ln Phi(N, T) + ln((T+1)(T+2)) + ln(1/delta) ) / n.

Code for gate t (it reads the first D_t wires: the d literals and the Boolean wires of earlier depth-1 gates):
    ln D_t                       fan-in f_t
    ln C(D_t, f_t)               which wires
    f_t ln(2Q)                   nonzero integer weights in {-Q..-1, 1..Q}
    ln(2 Q f_t + 2)              threshold b (a half-integer in the range of the integer pre-activation)
    ln 2                         whether the gate also becomes a wire
Readout: Phi(N, T) = 2 sum_{i<=T} C(N-1, i) sign patterns of a threshold of T real features on N points (Cover), with
N = min(2^d, prod_t (2 Q f_t + 1)) the size of the image of x -> (g_1(x), ..., g_T(x)) (a ReLU gate relu(s - b) of an integer
pre-activation s in [-Q f, Q f] takes at most 2 Q f + 1 values).

Writes study/RACE-BOUNDS.md and figures/race_bounds.png.
"""
import os, sys, math, json, time, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C
from models.race import Race

HERE = os.path.dirname(os.path.abspath(__file__))
DELTA = 0.05


def kl(p, q):
    p = min(max(p, 0.0), 1.0); q = min(max(q, 1e-15), 1 - 1e-15)
    return (p * math.log(p / q) if p > 0 else 0.0) + ((1 - p) * math.log((1 - p) / (1 - q)) if p < 1 else 0.0)


def klinv(p, eps):
    lo, hi = p, 1.0
    for _ in range(60):
        mid = (lo + hi) / 2
        lo, hi = (lo, mid) if kl(p, mid) > eps else (mid, hi)
    return hi


def lncomb(a, b):
    return math.lgamma(a + 1) - math.lgamma(b + 1) - math.lgamma(a - b + 1)


def ln_phi(N, T):
    """ln( 2 * sum_{i<=T} C(N-1, i) ), computed in log space."""
    terms = [lncomb(N - 1, i) for i in range(0, min(T, N - 1) + 1)]
    m = max(terms)
    return math.log(2) + m + math.log(sum(math.exp(t - m) for t in terms))


def circuit_cost(gates, d, Q):
    cost, lnN = 0.0, 0.0
    for (w, b, wire, kw, sd, mu) in gates:
        Dt = len(w); f = int(np.count_nonzero(w))
        cost += math.log(Dt) + lncomb(Dt, f) + f * math.log(2 * Q) + math.log(2 * Q * f + 2) + math.log(2)
        lnN += math.log(2 * Q * f + 1)
    lnN = min(lnN, d * math.log(2))
    return cost, lnN


def run(fns=None, ns=None, seeds=(0, 1, 2)):
    fns = fns or C.FNS; ns = ns or C.NS
    rows = []
    M = Race(theta=1.5, Q=3, gate="relu")
    for fn in fns:
        Xte, yte = C.test_data(fn)
        for n in ns:
            for s in seeds:
                X, y = C.train_data(fn, s, n)
                r = M.fit(X, y, np.random.default_rng([s, n, C._fn_seed(fn)]))
                # the fitted circuit lives in the predict closure (race.py's return value does not expose it)
                cl = {k: c.cell_contents for k, c in zip(r["predict"].__code__.co_freevars, r["predict"].__closure__)}
                G = cl["G_"]
                gates = [(gw, gb, gwire, None, gsd, gmu) for (gw, gb, gwire, gsd, gmu) in G]
                te = float(np.mean(r["predict"](Xte) != yte)); tr = float(np.mean(r["predict"](X) != y))
                T = len(gates)
                cost, lnN = circuit_cost(gates, C.D, 3)
                N = int(min(2 ** C.D, round(math.exp(lnN)))) if T else 1
                lphi = ln_phi(max(N, 2), T) if T else math.log(2)
                comp = cost + lphi + math.log((T + 1) * (T + 2)) + math.log(1 / DELTA)
                bound = klinv(tr, comp / n)
                rows.append(dict(fn=fn, n=n, seed=s, T=T, train_err=tr, test_err=te, ln_circuit=cost, ln_readout=lphi,
                                 complexity=comp, bound=min(bound, 1.0), fanins=[int(np.count_nonzero(g[0])) for g in gates]))
        print(f"{fn:11s} " + " ".join(f"{np.mean([r['bound'] for r in rows if r['fn']==fn and r['n']==n]):.2f}" for n in ns),
              flush=True)
    return rows


def report(rows):
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    ns = sorted({r["n"] for r in rows})
    L = ["# Occam bounds for the race model itself (generated by race_bounds_eval.py)", "",
         "Each fitted race predictor is bounded by its own circuit (prefix-free code over gates + Cover count of threshold readouts; "
         "delta = 0.05; see the script's docstring). Entries: mean over 3 seeds of the race model's actual test error / the bound, "
         "and the mean circuit size T.", "",
         "| fn | " + " | ".join(f"n={n}" for n in ns) + " |", "|---|" + "---|" * len(ns)]
    for fn in sorted({r["fn"] for r in rows}, key=C.FNS.index):
        cells = []
        for n in ns:
            rs = [r for r in rows if r["fn"] == fn and r["n"] == n]
            cells.append(f"{np.mean([r['test_err'] for r in rs]):.2f} / {np.mean([r['bound'] for r in rs]):.2f} (T={np.mean([r['T'] for r in rs]):.0f})")
        L.append(f"| {fn} | " + " | ".join(cells) + " |")
    nv = [r for r in rows if r["bound"] < 0.5]
    viol = [r for r in rows if r["bound"] < r["test_err"]]
    gen = [r for r in rows if r["test_err"] <= 0.1]
    L += ["", f"- Non-vacuous (< 0.5): {len(nv)} of {len(rows)} fits; bound < 0.2: {sum(r['bound'] < 0.2 for r in rows)}; "
          f"violations (bound below actual test error): {len(viol)}.",
          f"- Among fits that generalize (test error <= 0.1): median bound {np.median([r['bound'] for r in gen]):.3f}, "
          f"median circuit size {np.median([r['T'] for r in gen]):.0f}; among fits that do not: median size "
          f"{np.median([r['T'] for r in rows if r['test_err'] > 0.1]):.0f}.", ""]
    open(os.path.join(HERE, "RACE-BOUNDS.md"), "w").write("\n".join(L) + "\n")
    json.dump(rows, open(os.path.join(HERE, "race_bounds.json"), "w"), indent=0)
    fig, axs = plt.subplots(1, 2, figsize=(8.5, 3.8))
    for n, col in zip(ns, plt.cm.viridis(np.linspace(0, 0.95, len(ns)))):
        rs = [r for r in rows if r["n"] == n]
        axs[0].scatter([r["test_err"] for r in rs], [r["bound"] for r in rs], s=6, color=col, label=f"{n}")
        axs[1].scatter([r["T"] for r in rs], [r["test_err"] - r["train_err"] for r in rs], s=6, color=col)
    axs[0].plot([0, 1], [0, 1], "k:", lw=0.8); axs[0].set_xlabel("race test error"); axs[0].set_ylabel("Occam bound")
    axs[0].legend(fontsize=5, ncol=2, title="n", title_fontsize=6)
    axs[1].set_xlabel("circuit size T"); axs[1].set_ylabel("test - train error")
    fig.tight_layout(); fig.savefig(os.path.join(HERE, "figures", "race_bounds.png"), dpi=120); plt.close(fig)
    print("\n".join(L[-3:]))


if __name__ == "__main__":
    rows = run()
    report(rows)
