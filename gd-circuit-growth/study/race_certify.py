"""Are the race model's large generalizing circuits functionally small?  For a random sample of race fits that generalize
(test error <= 0.1) but end with T > 6 gates, apply the distillation certificate (certify.py) to the race predictor itself
and compare with the Occam bound computed from its own circuit (race_bounds.json).  Writes study/RACE-CERTIFY.md."""
import os, sys, json, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C, certify as K
from models.race import Race
HERE = os.path.dirname(os.path.abspath(__file__))
rows = json.load(open(os.path.join(HERE, "race_bounds.json")))
cand = [r for r in rows if r["test_err"] <= 0.1 and r["T"] > 6]
rng = np.random.default_rng(0)
pick = [cand[i] for i in sorted(rng.choice(len(cand), size=min(30, len(cand)), replace=False))]
M = Race(theta=1.5, Q=3, gate="relu"); out = []
for r in pick:
    fn, n, s = r["fn"], r["n"], r["seed"]
    X, y = C.train_data(fn, s, n)
    fit = M.fit(X, y, np.random.default_rng([s, n, C._fn_seed(fn)]))
    U = np.random.default_rng([C._fn_seed(fn), 99]).choice(np.array([-1.0, 1.0], dtype=np.float32), size=(16384, C.D))
    best, _ = K.certify(X, y, U, fit["predict"](U))
    out.append(dict(fn=fn, n=n, seed=s, T=r["T"], test_err=r["test_err"], occam_own=r["bound"], certificate=best["bound"],
                    cert_class=f"{best['kind']}(r={best['r']},k={best['k']},T={best['T']})"))
    print(out[-1], flush=True)
L = ["# Distillation certificates for the race model's large generalizing circuits (generated by race_certify.py)", "",
     "Sample of 30 race fits with test error <= 0.1 but more than 6 gates. 'Own Occam' bounds the predictor by its own circuit; "
     "'certificate' bounds it through a small junta / Fourier-sign circuit that agrees with it on unlabelled inputs (certify.py).", "",
     "| fn | n | seed | gates T | test err | own Occam bound | certificate | certifying class |", "|---|---|---|---|---|---|---|---|"]
for o in out:
    L.append(f"| {o['fn']} | {o['n']} | {o['seed']} | {o['T']} | {o['test_err']:.3f} | {o['occam_own']:.3f} | {o['certificate']:.3f} | {o['cert_class']} |")
L += ["", f"Median own-circuit Occam bound {np.median([o['occam_own'] for o in out]):.3f}; median certificate "
      f"{np.median([o['certificate'] for o in out]):.3f}; certificate below 0.2 in {sum(o['certificate'] < 0.2 for o in out)} of {len(out)}."]
open(os.path.join(HERE, "RACE-CERTIFY.md"), "w").write("\n".join(L) + "\n"); print("\n".join(L[-1:]))
