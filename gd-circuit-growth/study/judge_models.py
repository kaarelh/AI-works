"""Scoreboard of discrete models and baselines against the NN (fixed protocol, Adam).

Writes study/MODEL-SCOREBOARD.md, study/model_scoreboard.json and figures/model_*.png.
"""
import os, json, numpy as np
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
import common as C

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures"); os.makedirs(FIG, exist_ok=True)
EVALS = "/tmp/claude-0/-home-user-AI-works/addd33f6-5c52-5bee-997e-3f98d4e90609/scratchpad/model_evals"
MODELS = ["race", "sswm", "nngp-kernel", "occam-junta"]


def main():
    res = {m: C.load_eval(os.path.join(EVALS, f"{m}.npz")) for m in MODELS if os.path.exists(os.path.join(EVALS, f"{m}.npz"))}
    board = {}
    for m, r in res.items():
        for split, fns in (("HELDOUT", C.HELDOUT), ("CALIB", C.CALIB), ("ALL", C.FNS)):
            board[(m, split)] = C.compare(r, "adam", fns=fns, verbose=False)
    keys = [("sc_mean_abs_log2_ratio", "mean abs log2 n* ratio (lower better)"),
            ("sc_spearman", "n* Spearman"), ("success_agreement", "success agreement"),
            ("curve_mae", "curve MAE"), ("example_agreement_score", "per-example agreement"),
            ("time_spearman", "time Spearman")]
    L = ["# Discrete models vs. networks: scoreboard (generated by judge_models.py)", "",
         "Reference: muP MLP trained with Adam, fixed training set (3 seeds). n* = training-set size at which the "
         "seed-mean test error reaches 0.1 ('never' counted as 2 x 16384 for the ratio statistics). Per-example agreement: "
         "excess agreement with the network over independent errors, as a fraction of the maximum (same training set), "
         "on cells where the network is partially right. Time Spearman: network steps-to-generalise vs the model's own "
         "clock, over cells where both generalise. Models were calibrated on CALIB functions only.", ""]
    for split in ("HELDOUT", "CALIB", "ALL"):
        L += [f"## {split}", "", "| model | " + " | ".join(k[1] for k in keys) + " |", "|---|" + "---|" * len(keys)]
        for m in res:
            b = board[(m, split)]
            L.append(f"| {m} | " + " | ".join(f"{b[k]:.2f}" if b[k] == b[k] else "–" for k, _ in keys) + " |")
        L.append("")
    # per-function n*
    L += ["## Sample complexity n* per function", "", "| fn | split | NN Adam | " + " | ".join(res) + " |",
          "|---|---|---|" + "---|" * len(res)]
    fmt = lambda v: "never" if not np.isfinite(v) else f"{v:.0f}"
    for fn in C.FNS:
        nn = C.nn_fixed(fn, "adam"); sc_nn = C.sample_complexity(nn["ns"], nn["test_err"].mean(1))
        cells = []
        for m, r in res.items():
            e = np.nanmean(r["test_err"][fn], 1); ok = ~np.isnan(e)
            cells.append(fmt(C.sample_complexity(np.array(r["ns"])[ok], e[ok])))
        L.append(f"| {fn} | {'held-out' if fn in C.HELDOUT else 'calib'} | {fmt(sc_nn)} | " + " | ".join(cells) + " |")
    open(os.path.join(HERE, "MODEL-SCOREBOARD.md"), "w").write("\n".join(L) + "\n")
    json.dump({f"{m}|{s}": {k: v for k, v in b.items() if k != "partial_cells"} for (m, s), b in board.items()},
              open(os.path.join(HERE, "model_scoreboard.json"), "w"), indent=1, default=float)

    # figure: learning curves
    cols = 7; rows = int(np.ceil(len(C.FNS) / cols))
    fig, axs = plt.subplots(rows, cols, figsize=(2.6 * cols, 2.2 * rows), sharex=True, sharey=True)
    style = {"race": ("#2ca02c", "-"), "sswm": ("#9467bd", "-"), "nngp-kernel": ("#7f7f7f", "--"), "occam-junta": ("#d62728", ":")}
    for ax, fn in zip(axs.ravel(), C.FNS):
        nn = C.nn_fixed(fn, "adam")
        ax.semilogx(nn["ns"], nn["test_err"].mean(1), "o-", color="#1f77b4", ms=3, lw=2, label="NN (Adam)")
        for m, r in res.items():
            c, ls = style[m]; ax.semilogx(r["ns"], np.nanmean(r["test_err"][fn], 1), ls, color=c, lw=1.2, label=m)
        ax.set_title(fn + (" *" if fn in C.HELDOUT else ""), fontsize=9); ax.axhline(0.1, color="k", lw=0.4, ls=":")
    for ax in axs.ravel()[len(C.FNS):]:
        ax.axis("off")
    axs.ravel()[0].legend(fontsize=6); fig.supxlabel("training-set size n  (* = held-out function)"); fig.supylabel("test error")
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "model_learning_curves.png"), dpi=110); plt.close(fig)

    # figure: n* scatter
    fig, ax = plt.subplots(figsize=(4.6, 4.4)); cap = 2 * 16384
    for m, r in res.items():
        b = board[(m, "ALL")]
        xs = [min(p["n_nn"], cap) for p in b["per_fn"]]; ys = [min(p["n_model"], cap) for p in b["per_fn"]]
        held = [p["fn"] in C.HELDOUT for p in b["per_fn"]]
        c, _ = style[m]
        ax.scatter([x for x, h in zip(xs, held) if h], [y for y, h in zip(ys, held) if h], color=c, marker="o", s=22, label=f"{m} (held-out)")
        ax.scatter([x for x, h in zip(xs, held) if not h], [y for y, h in zip(ys, held) if not h], facecolors="none",
                   edgecolors=c, marker="o", s=22)
    ax.plot([10, cap], [10, cap], "k:", lw=0.8); ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlabel("n* of the network"); ax.set_ylabel("n* of the model (open = calibration fn; top row = never)")
    ax.legend(fontsize=6); fig.tight_layout(); fig.savefig(os.path.join(FIG, "model_nstar_scatter.png"), dpi=120); plt.close(fig)
    print("\n".join(L))


if __name__ == "__main__":
    main()
