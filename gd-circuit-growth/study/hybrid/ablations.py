"""Post-hoc attribution ablations of the frozen primary design (hyb_portfolio), run after the held-out results with the
constructor's `members` argument (the code is unchanged): which member families carry which result.
  toy (inputs permuted, full grid, 3 seeds): abl_noDFG = all members but DFG; abl_dfg = the DFG members alone (stacked);
  real (n <= 3000, seeds 0-1; 'eval_real.py --quick'): one member family alone (gbt, knn, et, lin), and all but kNN.
The full design's errors are taken from its held-out result files at the same (n, seed) cells.  Writes ABLATIONS.md.
usage: python ablations.py"""
import os, sys, json, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import compare_hybrid as CH
TH, DATA = CH.TH, CH.DATA
TOY = ["hyb_portfolio-perm", "abl_noDFG-perm", "abl_dfg-perm", "lin", "hgb"]
REAL = ["abl_gbt", "abl_knn", "abl_et", "abl_lin", "abl_noKNN"]


def toy_rows(suite):
    N = {}
    for L in TOY:
        r = CH.toy_load(L, suite)
        if r is not None:
            N[L] = {fn: TH.nstar(r["ns"], np.nanmean(np.array(v["err"], float), 1)) for fn, v in r["fns"].items()}
    NR = CH.toy_nstars(suite)
    return N, NR


def real_err(L, ds, ns, seeds=(0, 1)):
    """Seed-mean (seeds 0-1) test error at each n for learner L (the '-quick' file for ablations)."""
    r = CH.load(L, ds)
    if r is None:
        return None
    out = []
    for n in ns:
        if n not in r["ns"][:len(r["err"])]:
            out.append(np.nan); continue
        e = np.array(r["err"][r["ns"].index(n)], float); sd = r["seeds"]
        out.append(float(np.nanmean([e[sd.index(s)] for s in seeds if s in sd])))
    return out


def main():
    f = lambda v: "never" if not np.isfinite(v) else f"{v:.0f}"
    L = ["# Part 8: post-hoc attribution ablations of hyb_portfolio", "",
         "Generated by `ablations.py`. Run after the held-out results, with the frozen code (constructor argument `members`);",
         "labelled post hoc. They say which member families carry which result; they are not part of the held-out test.", ""]
    for suite in ("dlheld3", "designed"):
        N, NR = toy_rows(suite)
        if "abl_noDFG-perm" not in N:
            continue
        L += [f"## Toy suite `{suite}` (inputs permuted): n*", "",
              "| target | full | without DFG | DFG alone | lin | hgb | nets | nets_best |", "|---|---|---|---|---|---|---|---|"]
        for fn in NR["nets"]:
            L.append(f"| {fn} | " + " | ".join(f(N[k].get(fn, np.nan)) if k in N else "–" for k in TOY)
                     + f" | {f(NR['nets'][fn])} | {f(NR['nets_best'][fn])} |")
        L += ["", "| variant | vs nets_best: mean log2 n* ratio (both learn) | clearly better | clearly worse | never learned |",
              "|---|---|---|---|---|"]
        for k in TOY:
            if k in N:
                t = CH.toy_summary(N[k], NR["nets_best"])
                L.append(f"| {k} | {t['mean']:+.2f} | {t['better']} | {t['worse']} | {t['learner_never']} |")
        L.append("")
    names = list(DATA.HELDOUT2) + ["mnist", "fashion_mnist"]
    L += ["## Real tasks (fresh tabular set and images; n <= 3000, seeds 0-1): test error", "",
          "`best MLP` = per cell the lowest seed-mean (seeds 0-1) test error of the MLP variants.", "",
          "| dataset | n | full | " + " | ".join(k.replace("abl_", "") + (" only" if k != "abl_noKNN" else "")
                                           for k in REAL) + " | best MLP |", "|---|---|---|" + "---|" * (len(REAL) + 1)]
    agg = {k: [] for k in REAL}; agg_full = []
    for ds in names:
        full = CH.load("hyb_portfolio", ds)
        if full is None:
            continue
        ns = [n for n in full["ns"] if n <= 3000]
        ef = real_err("hyb_portfolio", ds, ns)
        E = {k: real_err(k + "-quick", ds, ns) for k in REAL}
        mb = []
        for n in ns:
            vals = [x for x in (real_err(v, ds, [n])[0] if CH.load(v, ds) else np.nan for v in CH.MLP_VARIANTS) if np.isfinite(x)]
            mb.append(min(vals) if vals else np.nan)
        for i, n in enumerate(ns):
            L.append(f"| {ds} | {n} | {ef[i]:.4f} | " + " | ".join("–" if E[k] is None else f"{E[k][i]:.4f}" for k in REAL)
                     + f" | {mb[i]:.4f} |")
            if np.isfinite(mb[i]):
                agg_full.append(np.log2(max(ef[i], 0.002) / max(mb[i], 0.002)))
                for k in REAL:
                    if E[k] is not None and np.isfinite(E[k][i]):
                        agg[k].append(np.log2(max(E[k][i], 0.002) / max(mb[i], 0.002)))
    L += ["", "| variant | cells | mean log2(err / best MLP err) |", "|---|---|---|",
          f"| full | {len(agg_full)} | {np.mean(agg_full):+.2f} |"]
    L += [f"| {k} | {len(v)} | {np.mean(v):+.2f} |" for k, v in agg.items() if v]
    open(os.path.join(HERE, "ABLATIONS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
