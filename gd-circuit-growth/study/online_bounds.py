"""Online-to-batch bounds for the one-pass (online) runs, from their logged prequential mistakes.

Each step trains on a fresh minibatch of 64 after predicting it, so the predictions on that batch are honest test
predictions.  For a window W of steps fixed in advance, with N = 64 |W| fresh samples and M prequential mistakes in it,
the average test error of the iterates in W (equivalently, the test error of a uniformly random iterate from W) is at most
M/N + sqrt(ln(1/delta)/(2N)) with probability >= 1 - delta (Azuma-Hoeffding; theory/C-bridge-and-certificates.md,
Proposition C4.1, and B3.4).  We use the windows "second half of training" and "last 2000 steps" (each at delta = 0.025),
and compare with the measured test error of the iterates at the checkpoints inside the window.
Writes study/ONLINE-BOUNDS.md.
"""
import os, math, numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
R = "/tmp/claude-0/-home-user-AI-works/addd33f6-5c52-5bee-997e-3f98d4e90609/scratchpad/results_online2"
FNS = ["par2", "par3", "maj9", "stair5", "majpar", "mux"]
DELTA = 0.025


def main():
    L = ["# Online-to-batch bounds for the one-pass runs (generated by online_bounds.py)", "",
         "One pass of Adam over fresh minibatches of 64, 20000 steps, 3 seeds. 'Bound' is the certified upper bound on the average "
         "test error of the iterates in the window (prequential mistake rate + sqrt(ln(1/delta)/(2N)), delta = 0.025 per window); "
         "'measured' is the average test error at the checkpoints inside the window. No capacity argument is used.", "",
         "| target | seed | samples to test error 0.1 | window: second half — prequential rate / bound / measured | window: last 2000 steps — bound / measured |",
         "|---|---|---|---|---|"]
    for fn in FNS:
        p = os.path.join(R, f"online_adam_{fn}.npz")
        if not os.path.exists(p):
            continue
        z = np.load(p)
        ps, pm = z["preq_steps"], z["preq_mistakes"]          # chunk end steps, mistakes per chunk [chunk, seed]
        starts = np.concatenate([[0], ps[:-1]])
        st, te = z["step"], z["test_err"]
        B = int(z["batch"]); T = int(ps[-1])
        for s in range(pm.shape[1]):
            hit = np.where(te[:, s] <= 0.1)[0]
            s2g = int(st[hit[0]]) * B if len(hit) else None
            cells = []
            for lo in (T // 2, T - 2000):
                sel = starts >= lo
                N = B * int((ps[sel] - starts[sel]).sum()); M = float(pm[sel, s].sum())
                bound = M / N + math.sqrt(math.log(1 / DELTA) / (2 * N))
                meas = float(te[(st > lo) & (st <= T), s].mean())
                cells.append((M / N, bound, meas))
            L.append(f"| {fn} | {s} | {s2g if s2g is not None else 'never'} | {cells[0][0]:.4f} / {cells[0][1]:.4f} / {cells[0][2]:.4f} | "
                     f"{cells[1][1]:.4f} / {cells[1][2]:.4f} |")
    open(os.path.join(HERE, "ONLINE-BOUNDS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
