"""d-scaling: how the networks' sample complexity n* grows with the input dimension d, and whether the race model (calibrated at
d = 30 only, constants unchanged) and the baselines reproduce it.

Usage:  python3 dscale_analysis.py eval 15     # evaluate race + NNGP at d = 15 (writes model_evals/*_d15.npz)
        python3 dscale_analysis.py eval 60
        python3 dscale_analysis.py report      # tables, exponents, figure -> study/DSCALE.md, figures/dscale.png
Run every command with DIM unset; the script sets the environment for each d itself (in subprocesses).
"""
import os, sys, json, subprocess, numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
EV = "/tmp/claude-0/-home-user-AI-works/addd33f6-5c52-5bee-997e-3f98d4e90609/scratchpad/model_evals"
FNS = ["par2", "par3", "par4", "stair5", "mux", "majpar", "maj9"]
DS = {15: 16384, 30: 16384, 60: 65536}


def _eval(d):
    os.environ["DIM"] = str(d); os.environ["NS_MAX"] = str(DS[d])
    sys.path.insert(0, HERE)
    import common as C
    from models.race import Race
    from models.baselines import NNGPKernel
    for M, tag in ((Race(theta=1.5, Q=3, gate="relu"), "race"), (NNGPKernel(max_n=4096), "nngp-kernel")):
        res = C.evaluate(M, fns=FNS, ns=C.NS, seeds=[0, 1])
        C.save_eval(res, f"{EV}/{tag}_d{d}.npz")


def _nstar_table():
    rows = {}
    for d in DS:
        env = dict(os.environ, DIM=str(d), NS_MAX=str(DS[d]), OPENBLAS_NUM_THREADS="1")
        code = f"""
import json, numpy as np, common as C, os
out = {{}}
for fn in {FNS!r}:
    r = {{}}
    try:
        nn = C.nn_fixed(fn, 'adam'); r['nn'] = C.sample_complexity(nn['ns'], nn['test_err'].mean(1))
        r['nn_err'] = [float(x) for x in nn['test_err'].mean(1)]; r['ns'] = [int(x) for x in nn['ns']]
    except FileNotFoundError:
        pass
    for tag in ('race', 'nngp-kernel'):
        p = '{EV}/' + tag + ('' if {d} == 30 else '_d{d}') + '.npz'
        if os.path.exists(p):
            e = C.load_eval(p); m = np.nanmean(e['test_err'][fn], 1); ok = ~np.isnan(m)
            r[tag] = C.sample_complexity(np.array(e['ns'])[ok], m[ok])
            r[tag + '_err'] = [float(x) for x in m]
    out[fn] = r
print(json.dumps(out, default=float))
"""
        res = subprocess.run([sys.executable, "-c", code], cwd=HERE, env=env, capture_output=True, text=True)
        rows[d] = json.loads(res.stdout.strip().splitlines()[-1].replace("Infinity", "1e99"))
    return rows


def report():
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    rows = _nstar_table()
    f = lambda v: "–" if v is None else ("never" if v >= 1e98 else f"{v:.0f}")
    L = ["# d-scaling of sample complexity (generated by dscale_analysis.py)", "",
         "n* = training-set size at which the seed-mean test error reaches 0.1 (networks: 3 seeds at d = 30, 2 seeds at d = 15, 60). "
         "The race model uses its d = 30 calibration unchanged. Exponent = least-squares slope of log n* against log d over the d values "
         "where n* is finite.", "",
         "| target | NN n* at d = 15 / 30 / 60 | NN exponent | race n* at d = 15 / 30 / 60 | race exponent | NNGP n* at d = 15 / 30 / 60 |",
         "|---|---|---|---|---|---|"]
    exps = {}
    for fn in FNS:
        cells, ex = [], {}
        for key in ("nn", "race", "nngp-kernel"):
            vals = [rows[d].get(fn, {}).get(key) for d in DS]
            cells.append(" / ".join(f(v) for v in vals))
            pts = [(d, v) for d, v in zip(DS, vals) if v is not None and v < 1e98]
            ex[key] = np.polyfit(np.log([p[0] for p in pts]), np.log([p[1] for p in pts]), 1)[0] if len(pts) >= 2 else None
        exps[fn] = ex
        g = lambda v: "–" if v is None else f"{v:.2f}"
        L.append(f"| {fn} | {cells[0]} | {g(ex['nn'])} | {cells[1]} | {g(ex['race'])} | {cells[2]} |")
    L += ["", "Prediction error of the race model, |log2(n*_race / n*_NN)| per target (mean over the 7 targets in the last column):", "",
          "| d | " + " | ".join(FNS) + " | mean |", "|---|" + "---|" * (len(FNS) + 1)]
    for d in DS:
        errs = []
        for fn in FNS:
            a, b = rows[d].get(fn, {}).get("race"), rows[d].get(fn, {}).get("nn")
            errs.append(abs(np.log2(a / b)) if a and b and a < 1e98 and b < 1e98 else np.nan)
        L.append(f"| {d}{' (calibration)' if d == 30 else ''} | " + " | ".join("–" if np.isnan(e) else f"{e:.2f}" for e in errs)
                 + f" | {np.nanmean(errs):.2f} |")
    open(os.path.join(HERE, "DSCALE.md"), "w").write("\n".join(L) + "\n")
    json.dump(dict(rows=rows, exponents=exps), open(os.path.join(HERE, "dscale.json"), "w"), indent=1, default=float)
    fig, axs = plt.subplots(1, len(FNS), figsize=(2.6 * len(FNS), 2.6), sharey=True)
    for ax, fn in zip(axs, FNS):
        for key, col, mk in (("nn", "#1f77b4", "o"), ("race", "#2ca02c", "s"), ("nngp-kernel", "#7f7f7f", "^")):
            pts = [(d, rows[d].get(fn, {}).get(key)) for d in DS]
            pts = [(d, v) for d, v in pts if v is not None and v < 1e98]
            if pts:
                ax.loglog([p[0] for p in pts], [p[1] for p in pts], mk + "-", color=col, label=key, ms=4)
        ax.set_title(fn, fontsize=9); ax.set_xticks([15, 30, 60]); ax.set_xticklabels(["15", "30", "60"])
    axs[0].set_ylabel("n*"); axs[0].legend(fontsize=6); fig.supxlabel("input dimension d"); fig.tight_layout()
    fig.savefig(os.path.join(HERE, "figures", "dscale.png"), dpi=120); plt.close(fig)
    print("\n".join(L))


if __name__ == "__main__":
    if sys.argv[1] == "eval":
        _eval(int(sys.argv[2]))
    else:
        report()
