"""Out-of-sample test of the models on 20 fresh random formulas (SUITE=random): race (d = 30 calibration, unchanged),
sswm, and the two baselines, scored against the networks.  Every function here is held out for every model."""
import os, sys
os.environ["SUITE"] = "random"
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np, common as C
from models.race import Race
from models.sswm import SSWM
from models.baselines import NNGPKernel, OccamJunta
EV = "/tmp/claude-0/-home-user-AI-works/addd33f6-5c52-5bee-997e-3f98d4e90609/scratchpad/model_evals"
models = [Race(theta=1.5, Q=3, gate="relu"), SSWM(), NNGPKernel(max_n=4096), OccamJunta()]
for M in models:
    p = f"{EV}/{M.name}_random.npz"
    if not os.path.exists(p):
        C.save_eval(C.evaluate(M, seeds=[0, 1], verbose=False), p)
L = ["# Out-of-sample targets: 20 fresh random formulas (generated by run_random_models.py)", "",
     "Networks: muP MLP, Adam, 2 seeds per (target, n). Models use their original calibration unchanged; none has seen these targets.", "",
     "| model | mean abs log2 n* ratio | n* Spearman | success agreement | curve MAE | per-example agreement | time Spearman |",
     "|---|---|---|---|---|---|---|"]
per = {}
for M in models:
    r = C.load_eval(f"{EV}/{M.name}_random.npz")
    b = C.compare(r, "adam", verbose=False)
    per[M.name] = b
    L.append(f"| {M.name} | {b['sc_mean_abs_log2_ratio']:.2f} | {b['sc_spearman']:.2f} | {b['success_agreement']:.2f} | "
             f"{b['curve_mae']:.3f} | {b['example_agreement_score']:.2f} | {b['time_spearman']:.2f} |")
fmt = lambda v: "never" if not np.isfinite(v) else f"{v:.0f}"
L += ["", "| target | description | NN n* | " + " | ".join(m.name for m in models) + " |", "|---|---|---|" + "---|" * len(models)]
for i, fn in enumerate(C.FNS):
    L.append(f"| {fn} | {C.SUITE[fn]['desc'][:48]} | {fmt(per[models[0].name]['per_fn'][i]['n_nn'])} | "
             + " | ".join(fmt(per[m.name]['per_fn'][i]['n_model']) for m in models) + " |")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "RANDOM-SUITE.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
