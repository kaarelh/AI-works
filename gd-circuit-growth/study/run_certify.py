"""Batch distillation certificates for the trained networks (fixed protocol, Adam).

E1  final networks: every function, n in {64, 256, 1024, 4096, 16384}, seeds 0-2; 16384 fresh unlabelled inputs
    drawn here (half to fit the circuit, half to estimate disagreement), network evaluated from its saved parameters.
E2  over training time: a few (function, n), seed 0, at every checkpoint, using the saved test-set predictions as the
    unlabelled pool (2048 + 2048).
Writes study/certificates.json, study/CERTIFICATES.md and study/figures/cert_*.png.
"""
import os, json, sys, time, numpy as np
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
import common as C, certify as K

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures"); os.makedirs(FIG, exist_ok=True)


def nn_forward(P, j, X):
    W1, b1, W2, b2, a = (P[k][j].astype(np.float32) for k in ("W1", "b1", "W2", "b2", "a"))
    h1 = np.maximum(X @ W1.T + b1, 0); h2 = np.maximum(h1 @ W2.T + b2, 0)
    return h2 @ a


def e1(ns=(64, 256, 1024, 4096, 16384), seeds=(0, 1, 2)):
    out = []
    for fn in C.FNS:
        z = np.load(os.path.join(C.RESULTS, f"fixed_adam_{fn}.npz"))
        P = np.load(os.path.join(C.RESULTS, f"params_fixed_adam_{fn}.npz"))
        Xte, yte = C.test_data(fn)
        rng = np.random.default_rng([C._fn_seed(fn), 4242])
        U = rng.choice(np.array([-1.0, 1.0], dtype=np.float32), size=(16384, C.D))
        for n in ns:
            for s in seeds:
                j = [i for i, (n_, s_) in enumerate(zip(z["net_n"], z["net_s"])) if n_ == n and s_ == s][0]
                X, y = C.train_data(fn, s, n)
                h = np.where(nn_forward(P, j, U) >= 0, 1.0, -1.0)
                hte = np.where(nn_forward(P, j, Xte) >= 0, 1.0, -1.0)
                t0 = time.time()
                best, rows = K.certify(X, y, U, h)
                out.append(dict(fn=fn, n=n, seed=s, test_err=float(np.mean(hte != yte)),
                                train_err=float(z["train_err"][-1, j]), **{f"cert_{k}": v for k, v in best.items()}))
                print(f"E1 {fn:11s} n={n:5d} s={s} test {out[-1]['test_err']:.3f} cert {best['bound']:.3f} "
                      f"({best['kind']} r={best['r']} k={best['k']} T={best['T']}, g-train {best['train_err_g']:.3f}, "
                      f"disagree {best['disagree']:.3f}, occam {best['occam']:.3f})  {time.time()-t0:.1f}s", flush=True)
    return out


def e2(cases=(("par3", 1024), ("par3", 4096), ("stair5", 4096), ("majpar", 4096), ("maj9", 1024), ("mux", 4096),
              ("rand1", 4096), ("dnf3", 16384))):
    out = []
    for fn, n in cases:
        z = np.load(os.path.join(C.RESULTS, f"fixed_adam_{fn}.npz"))
        j = [i for i, (n_, s_) in enumerate(zip(z["net_n"], z["net_s"])) if n_ == n and s_ == 0][0]
        Xte, yte = C.test_data(fn); X, y = C.train_data(fn, 0, n)
        for c, step in enumerate(z["step"]):
            h = z["pred"][c, j].astype(float)
            best, _ = K.certify(X, y, Xte, h)
            out.append(dict(fn=fn, n=n, step=int(step), test_err=float(z["test_err"][c, j]),
                            train_err=float(z["train_err"][c, j]), **{f"cert_{k}": v for k, v in best.items()}))
            print(f"E2 {fn} n={n} step {step:6d} train {out[-1]['train_err']:.3f} test {out[-1]['test_err']:.3f} "
                  f"cert {best['bound']:.3f} ({best['kind']} r={best['r']} T={best['T']} lnH={best['ln_class']:.1f})", flush=True)
    return out


def report(E1, E2):
    L = ["# Distillation certificates (generated by run_certify.py)", "",
         "Certified upper bound on the network's test error from the training set and unlabelled inputs only "
         "(delta = 0.05 per network; see certify.py for the exact inequality). 'size' is the circuit class used by the "
         "best certificate: junta(r) or chars(r, k, T).", "",
         "| fn | n | NN test err (mean) | certificate (mean) | best class (seed 0) | ln-class size |", "|---|---|---|---|---|---|"]
    for fn in C.FNS:
        for n in sorted({r["n"] for r in E1}):
            rs = [r for r in E1 if r["fn"] == fn and r["n"] == n]
            if not rs:
                continue
            r0 = rs[0]
            cls = f"junta({r0['cert_r']})" if r0["cert_kind"] == "junta" else f"chars({r0['cert_r']},{r0['cert_k']},{r0['cert_T']})"
            L.append(f"| {fn} | {n} | {np.mean([r['test_err'] for r in rs]):.3f} | {np.mean([r['cert_bound'] for r in rs]):.3f} "
                     f"| {cls} | {r0['cert_ln_class']:.1f} |")
    nonvac = [r for r in E1 if r["cert_bound"] < 0.5]
    L += ["", f"Non-vacuous (< 0.5) certificates: {len(nonvac)} of {len(E1)} networks; certificate < 0.2: "
          f"{sum(r['cert_bound'] < 0.2 for r in E1)}; violations (certificate below actual test error): "
          f"{sum(r['cert_bound'] < r['test_err'] for r in E1)}.", ""]
    open(os.path.join(HERE, "CERTIFICATES.md"), "w").write("\n".join(L) + "\n")
    # scatter
    fig, ax = plt.subplots(figsize=(4.2, 4))
    for n, col in zip(sorted({r["n"] for r in E1}), plt.cm.viridis(np.linspace(0, 0.9, 5))):
        rs = [r for r in E1 if r["n"] == n]
        ax.scatter([r["test_err"] for r in rs], [r["cert_bound"] for r in rs], s=10, color=col, label=f"n={n}")
    ax.plot([0, 1], [0, 1], "k:", lw=0.8); ax.set_xlabel("actual test error"); ax.set_ylabel("certified bound")
    ax.set_xlim(-0.02, 0.55); ax.set_ylim(-0.02, 1.02); ax.legend(fontsize=7); fig.tight_layout()
    fig.savefig(os.path.join(FIG, "cert_scatter.png"), dpi=120); plt.close(fig)
    # over time
    cases = sorted({(r["fn"], r["n"]) for r in E2})
    fig, axs = plt.subplots(2, (len(cases) + 1) // 2, figsize=(3.2 * ((len(cases) + 1) // 2), 5.4), sharey=True)
    for ax, (fn, n) in zip(axs.ravel(), cases):
        rs = sorted([r for r in E2 if r["fn"] == fn and r["n"] == n], key=lambda r: r["step"])
        st = np.maximum([r["step"] for r in rs], 1)
        ax.semilogx(st, [r["train_err"] for r in rs], label="train err"); ax.semilogx(st, [r["test_err"] for r in rs], label="test err")
        ax.semilogx(st, [r["cert_bound"] for r in rs], label="certificate"); ax.set_title(f"{fn}, n={n}", fontsize=9)
        ax2 = ax.twinx(); ax2.semilogx(st, [r["cert_ln_class"] for r in rs], "k:", lw=0.8); ax2.set_yticks([])
    axs.ravel()[0].legend(fontsize=6); fig.supxlabel("training step (dotted: ln size of certifying class)"); fig.tight_layout()
    fig.savefig(os.path.join(FIG, "cert_over_time.png"), dpi=110); plt.close(fig)


if __name__ == "__main__":
    which = sys.argv[1] if len(sys.argv) > 1 else "both"
    path = os.path.join(HERE, "certificates.json")
    data = json.load(open(path)) if os.path.exists(path) else {}
    if which in ("e1", "both"):
        data["E1"] = e1()
        json.dump(data, open(path, "w"), indent=1)
    if which in ("e2", "both"):
        data["E2"] = e2()
        json.dump(data, open(path, "w"), indent=1)
    report(data.get("E1", []), data.get("E2", []))
