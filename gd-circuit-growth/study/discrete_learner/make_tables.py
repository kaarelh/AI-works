"""Collect every results/*.json into RESULTS.md (tables generated from the JSON; nothing typed by hand).

Sections: main comparison (designed, random, held-out suites at d = 30), d-scaling (d = 15, 60, 120), ablations.
"""
import os, json, glob, io, contextlib, numpy as np
import harness as H

HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, "results")


def load(name):
    p = os.path.join(RES, name + ".json")
    return json.load(open(p)) if os.path.exists(p) else None


def merged_heldout():
    a, b = load("dfg-c1.0__dlheld"), load("dfg-c1.0__dlheld_b")
    if a is None:
        return None
    if b is not None:
        a["fns"].update(b["fns"])
    return a


ROWS = [  # (key, label); key "V1HELD" = the frozen v1 held-out run (written in two halves)
    ("dfg-v1.1-perm__dlheld2", "held-out 2 (7 targets), v1.1, inputs permuted per fit - blind"),
    ("dfg-c1.0-Khi4__dlheld", "held-out 1 (12), frozen v1 without the degree-5/6 search - blind"),
    ("V1HELD", "held-out 1 (12), frozen v1 (degree-5/6 search added knowing par5 was in the suite)"),
    ("dfg-v1.1__dlheld", "held-out 1 (12), v1.1 - post-hoc"),
    ("dfg-c1.0__random", "random formulas (20), v1 - used as a check during development"),
    ("dfg-v1.1__random", "random formulas (20), v1.1"),
    ("dfg-c1.0__designed", "designed (21), v1 - in-sample"),
    ("dfg-v1.1__designed", "designed (21), v1.1 - in-sample"),
    ("dfg-c1.0__designed_d15", "designed at d = 15 (7), v1 (the budget does not bind at d = 15)"),
    ("dfg-v1.1__designed_d60", "designed at d = 60 (7), v1.1"),
    ("dfg-v1.1__designed_d120", "designed at d = 120 (4), v1.1"),
]


def table(res):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        out = H.report(res)
    return buf.getvalue(), out


def summary_row(res, label):
    ratios, lw, ll, n = [], 0, 0, 0
    for name, r in res["fns"].items():
        ln = H.nstar(res["ns"], np.nanmean(np.array(r["err"]), 1))
        nn = H.nstar(H.NS, np.nanmean(np.array(r["nn_err"]), 1)) if r["nn_err"] is not None else float("nan")
        n += 1
        if np.isfinite(ln) and np.isfinite(nn):
            ratios.append(np.log2(ln / nn))
        lw += (np.isfinite(ln) and (not np.isfinite(nn) or np.log2(ln / nn) < -0.25))
        ll += (np.isfinite(nn) and (not np.isfinite(ln) or np.log2(ln / nn) > 0.25))
    fl = max(np.nanmax(np.array(r["flops"])) for r in res["fns"].values()) / res["gd_flops"]
    med = float(np.median(ratios)) if ratios else float("nan")
    _, out = table(res)
    return (f"| {label} | {lw} | {ll} | {2 ** -med:.1f}x | {2 ** -np.mean(ratios):.1f}x | "
            f"{len(out['worse_cells'])} ({len(out['worse_sig'])}) of {out['cells']} | {fl:.2f} |")


def main():
    L = ["# DFG against the networks: all results", "",
         "Generated by `make_tables.py` from `results/*.json` (each written by `run_eval.py`).  n* = training-set size at",
         "which the seed-mean test error reaches 0.1 (log-interpolated on the grid 16..16384); networks: the study's",
         "fixed-n Adam runs (muP MLP d-128-128-1, batch 64, 20000 steps, 40000 at d = 120; 3 seeds at d = 30, 2 at other d).",
         "log2 ratio < 0 means DFG needs less data.  'max FLOPs / GD run' is DFG's largest per-fit compute over the grid, as a",
         "fraction of one network run (6 P x 64 x steps + Adam).  The data factors are over targets both learners learn (a",
         "target DFG never learns counts as 'clearly worse' and is left out of them).  The s.e. is from the seed-to-seed spread",
         "of both learners.", "",
         "## Summary", "",
         "| suite, learner | DFG clearly better (n* ratio < 2^-0.25, or networks never) | clearly worse | median data factor (networks' n* / DFG's) | geometric-mean data factor | (target, n) cells where DFG's error exceeds the networks' by > 0.02 (of these, by > 2 s.e.) | max FLOPs per fit / one GD run |",
         "|---|---|---|---|---|---|---|"]
    blocks = []
    for key, label in ROWS:
        res = merged_heldout() if key == "V1HELD" else load(key)
        if res is None:
            continue
        res["suite"] = label
        L.append(summary_row(res, label))
        blocks.append(table(res)[0])
    L += ["", "## Per-suite tables", ""] + blocks
    abl = sorted(glob.glob(os.path.join(RES, "abl-*__designed.json")))
    if abl:
        rs = {json.load(open(p))["learner"]: json.load(open(p)) for p in abl}
        full = rs.get("abl-full-perm")
        fns = list(full["fns"]) if full else list(next(iter(rs.values()))["fns"])
        nst = lambda r, f: H.nstar(r["ns"], np.nanmean(np.array(r["fns"][f]["err"]), 1))
        L += ["## Ablations (DFG v1.1, inputs permuted per fit; 7 designed targets, d = 30)", "",
              "n* of each variant (the networks' n* in the last row). Each variant removes one ingredient.", "",
              "| variant | " + " | ".join(fns) + " | mean log2 n* vs full |", "|---|" + "---|" * (len(fns) + 1)]
        order = ["abl-full-perm"] + [k for k in rs if k != "abl-full-perm"]
        for k in order:
            r = rs[k]; vals = [nst(r, f) for f in fns]
            ml = np.mean([min(np.log2(v / nst(full, f)), 8.0) if np.isfinite(v) else 8.0 for v, f in zip(vals, fns)]) if full else float("nan")
            L.append(f"| {k.replace('abl-', '').replace('-perm', '')} | " + " | ".join("never" if not np.isfinite(v) else f"{v:.0f}" for v in vals) + f" | {ml:+.2f} |")
        L.append("| networks | " + " | ".join(f"{H.nstar(H.NS, np.nanmean(np.array(full['fns'][f]['nn_err']), 1)):.0f}" for f in fns) + " | |")
        L += ["", "(A target never learned counts +8 in the mean.)", ""]
    open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L[:20]))


if __name__ == "__main__":
    main()
