"""Referee 5: re-run of the new parts of E6 (slack-imitation.md, version 2).

1. SI-V-ABC (one_human_verifier_abc) at n = 16 and n = 64, all five kinds, alpha = 0.1 and 0.3,
   with the seeds of main_verifier_abc (1000 n + s, s < 40). Compared field by field with
   results/slack_imitation_verifier_abc.json.
2. Chained imitation without slack on the same humans (main_same) at n = 16 and 64 (n0 = 8, 32),
   all five kinds, same seeds and caps. Compared with results/slack_imitation_same.json.
3. The markdown table regenerated by table() from copies of the saved JSON files in a scratch
   directory, and compared byte for byte with results/slack_imitation_table.md.

Nothing under results/ or code/ is written. Usage: python3 referee5_rerun.py [SCRATCH_DIR]
"""

import filecmp
import json
import os
import shutil
import sys
import tempfile
import time
from multiprocessing import Pool

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "code"))
import slack_imitation as si  # noqa: E402

import numpy as np  # noqa: E402

RES = os.path.join(ROOT, "results")
H = 40


def close(a, b):
    return abs(a - b) <= 1e-9 * max(1.0, abs(a), abs(b))


def part1(pool):
    saved = json.load(open(os.path.join(RES, "slack_imitation_verifier_abc.json")))
    print("Part 1: SI-V-ABC re-run (40 humans per cell)")
    bad = 0
    for alpha in (0.1, 0.3):
        for n in (16, 64):
            for kind in si.KINDS:
                rows = pool.map(si.one_human_verifier_abc,
                                [(kind, n, n // 2, 1000 * n + s, alpha) for s in range(H)])
                q = np.array([r[0] for r in rows], dtype=float)
                mine = dict(task_mean=float(q.mean()),
                            task_sem=float(q.std(ddof=1) / np.sqrt(H)),
                            asked_mean=float(np.mean([r[1] for r in rows])),
                            rejected_mean=float(np.mean([r[2] for r in rows])))
                key = f"{kind}_n{n}_sigma{n // 2}_SIV-ABC_alpha{alpha}"
                ref = saved[key]
                ok = all(close(mine[f], ref[f]) for f in mine)
                bad += not ok
                print(f"  {key:40s} task {mine['task_mean']:8.2f} (saved {ref['task_mean']:8.2f})"
                      f"  asked {mine['asked_mean']:7.2f}  rejected {mine['rejected_mean']:6.3f}"
                      f"  {'MATCH' if ok else 'DIFFER'}")
    print(f"  cells that differ: {bad}")


def part2(pool):
    saved = json.load(open(os.path.join(RES, "slack_imitation_same.json")))
    print("\nPart 2: chained imitation without slack, same humans (40 humans per cell)")
    bad = 0
    for n in (16, 64):
        n0 = n // 2
        for kind in si.KINDS:
            rows = pool.map(si.one_human, [(kind, n0, 0, "CI", 1000 * n + s, 40 * si.M * n0)
                                           for s in range(H)])
            mine = si.summarise(rows)
            key = f"{kind}_n{n}_same_CI_n0"
            ref = saved[key]
            fields = ["task_mean", "task_sem", "task_median", "final_failure_mean",
                      "mistake_hits_mean", "reached"]
            ok = all(close(mine[f], ref[f]) for f in fields)
            bad += not ok
            print(f"  {key:28s} task {mine['task_mean']:9.2f} (saved {ref['task_mean']:9.2f})"
                  f"  {'MATCH' if ok else 'DIFFER'}")
    # the same humans: t_p and k_p of the slack cell and of the no-slack cell agree
    same = 0
    for n in (16, 64, 256):
        for s in range(H):
            r1 = np.random.default_rng(1000 * n + s)
            r2 = np.random.default_rng(1000 * n + s)
            tp1 = r1.integers(0, n - n // 2, size=si.M); kp1 = r1.random(si.M)
            tp2 = r2.integers(0, n // 2 - 0, size=si.M); kp2 = r2.random(si.M)
            same += bool((tp1 == tp2).all() and (kp1 == kp2).all())
    print(f"  seeds whose (t_p, k_p) agree between the slack and the same-humans cells: {same} of {3 * H}")
    print(f"  cells that differ: {bad}")


def part3(scratch):
    print("\nPart 3: the table regenerated from the saved JSON files")
    d = tempfile.mkdtemp(dir=scratch)
    for name in ["slack_imitation_summary.json", "slack_imitation_mix.json",
                 "slack_imitation_same.json", "slack_imitation_verifier.json",
                 "slack_imitation_verifier_abc.json"]:
        shutil.copy(os.path.join(RES, name), d)
    import contextlib
    import io
    with contextlib.redirect_stdout(io.StringIO()):
        si.table(d)
    same = filecmp.cmp(os.path.join(d, "slack_imitation_table.md"),
                       os.path.join(RES, "slack_imitation_table.md"), shallow=False)
    print(f"  regenerated table identical to results/slack_imitation_table.md: {same}")
    # the note's two tables against the generated file
    note = open(os.path.join(ROOT, "slack-imitation.md")).read().splitlines()
    gen = open(os.path.join(RES, "slack_imitation_table.md")).read().splitlines()
    gen_rows = [g for g in gen if g.startswith("| ") and not g.startswith("| protocol")]
    missing = [g for g in gen_rows if g not in note]
    print(f"  generated table rows not found verbatim in slack-imitation.md: {len(missing)}")
    for g in missing:
        print("   ", g)


def main():
    scratch = sys.argv[1] if len(sys.argv) > 1 else tempfile.gettempdir()
    t0 = time.time()
    with Pool(4) as pool:
        part1(pool)
        part2(pool)
    part3(scratch)
    print(f"\n[{time.time() - t0:.0f} s]")


if __name__ == "__main__":
    main()
