"""Thread B experiment (E5): insights drawn from a rarely used, elicitable knowledge base.

The class is the hidden-insight class of note.md, Theorem 3, with the insight content
moved into a knowledge base that the human can be asked about.

  * L topics, m = 2L problems; problem p has a visible topic u_p = p mod L, so each
    topic is used by two problems (a rarely used piece of knowledge).
  * Topic l has a technique with probability eta: a stage s_l, uniform on {0..n-1},
    and a content k_l, a fresh label (q -> infinity). Otherwise s_l = "none".
  * The human is silent (Theorem 3's class): on problem p it writes k_{u_p} exactly at
    step s_{u_p} and copies it forward; on a state lacking it later it carries on.
    States are (p, j, a) with a = None (no insight yet) or a content.
  * A run fails if it differs from the human's run.

Probes are asked once per topic, before any task query ("what do you know about topic
l?"). The answer depends on the probe type and on whether the human recalls the
technique when asked (probability phi; unrecalled techniques, like absent ones, get
the answer "nothing comes to mind"):

  presence(phi)       recalled: only "I know a technique for this topic".
  content(phi)        recalled: the content k_l only. The stage is generated by the
                      work (not known to the human in advance).
  full(phi)           recalled: content and stage ("I'd use it at stage s").
  window(phi, w)      recalled: content and the aligned block of w steps holding s_l.
  misreport(phi, psi) recalled: content and a stated stage, which is s_l with
                      probability 1 - psi and a uniform other step otherwise. The
                      learner's prior knows psi (< 1/2), so it trusts the report.

Task protocols after the probes (at most one task query per round, no checks). Each
round draws a uniform problem; no protocol except CIall asks about a topic on which the
posterior is already certain (stage and content known, or, after probes with phi = 1, an
answer "nothing", which then means there is no technique):

  CIall chained imitation exactly as in E1: a uniform step of the decoder's run, every
        round;
  CI    the same, skipping topics on which the posterior is certain;
  LOC   a uniform step of the reported window when there is one, else uniform;
  VER   the stated stage while it is untested (verify the report), else uniform;
  MB    reference: monitored bisection with the perfect check (as in E1).

Posteriors are exact under the class prior (topics are independent). With q -> inf the
majority decoder writes a content only if the content is known and one step has
posterior probability of being the stage above 1/2 (ties go to "no insight"). We stop
the first time the exact failure probability on a fresh uniform problem is <= eps (an
oracle stopping rule that measures cost, as in E1 and E3).

We also record R_T, the realised residual -log2 posterior(theta | probe answers) under
the class prior, with contents counted as 20-bit labels: the bound of Theorem 1 of the
report on the number of task queries that can land on a mistake.

Usage: python3 threadB_kb_probes.py OUTDIR
"""

import json
import math
import os
import sys

import numpy as np

CONTENT_BITS = 20  # contents counted as 20-bit labels for the residual (q = 2^20)


class Topic:
    __slots__ = ("s", "found", "content", "excl", "region", "stated", "none_known")

    def __init__(self, s):
        self.s = s              # true stage, n means "no technique"
        self.found = False      # stage and content known to the learner
        self.content = False    # content known to the learner
        self.excl = set()       # steps tested and answered "no insight here"
        self.region = None      # (lo, hi): reported window for the stage
        self.stated = None      # stated stage (misreport probes)
        self.none_known = False  # certain that the topic has no technique


def write_step(tp, n):
    """Step at which the majority decoder writes the content, or None."""
    if tp.found:
        return tp.s
    if tp.none_known or not tp.content:
        return None
    if tp.stated is not None and tp.stated not in tp.excl:
        return tp.stated  # posterior (1-psi)/(...) > 1/2 while untested
    lo, hi = tp.region if tp.region is not None else (0, n)
    cand = [j for j in range(lo, hi) if j not in tp.excl and j != tp.stated]
    # with the content known a technique is certain; the stage is uniform on cand
    return cand[0] if len(cand) == 1 else None


def is_bad(tp, n):
    """Does the decoder's run on this topic's problems differ from the human's?"""
    if tp.s == n:
        return write_step(tp, n) is not None
    return write_step(tp, n) != tp.s  # a write step is only returned for a known content


def residual_bits(tp, kind, n, eta, phi, w, psi):
    """-log2 posterior of this topic's parameters given its probe answer."""
    tech = tp.s < n
    if kind == "none":
        return (math.log2(1 / eta) + math.log2(n) + CONTENT_BITS) if tech \
            else math.log2(1 / (1 - eta))
    if kind == "presence" and tech and phi >= 1.0:
        return math.log2(n) + CONTENT_BITS
    if not (tech and tp.content):
        # the answer was "nothing comes to mind": absent, or present and not recalled
        z = eta * (1 - phi) + (1 - eta)
        if tech:
            return -math.log2(eta * (1 - phi) / z) + math.log2(n) + CONTENT_BITS
        return -math.log2((1 - eta) / z)
    if kind == "content":
        return math.log2(n)
    if kind == "full":
        return 0.0
    if kind == "window":
        return math.log2(tp.region[1] - tp.region[0])
    if kind == "misreport":
        return -math.log2(1 - psi) if tp.stated == tp.s else -math.log2(psi / (n - 1))
    raise ValueError(kind)


def make_truth(rng, L, n, eta):
    tech = rng.random(L) < eta
    return np.where(tech, rng.integers(0, n, size=L), n)


def apply_probes(topics, rng, kind, n, phi, w, psi):
    probes = 0
    for tp in topics:
        probes += 1
        if kind == "none":
            probes -= 1
            continue
        if tp.s == n or rng.random() >= phi:
            # "nothing comes to mind"; with phi = 1 this means there is no technique
            tp.none_known = phi >= 1.0
            continue
        if kind == "presence":
            pass  # the learner learns only that a technique exists
        elif kind == "content":
            tp.content = True
        elif kind == "full":
            tp.content = True
            tp.found = True
        elif kind == "window":
            tp.content = True
            lo = (tp.s // w) * w
            tp.region = (lo, min(lo + w, n))
            if tp.region[1] - tp.region[0] == 1:
                tp.found = True
        elif kind == "misreport":
            tp.content = True
            if rng.random() < psi:
                other = int(rng.integers(n - 1))
                tp.stated = other if other < tp.s else other + 1
            else:
                tp.stated = tp.s
        else:
            raise ValueError(kind)
    return probes


def run_one(seed_truth, seed_proto, L, n, eta, eps, kind, proto, phi=1.0, w=1, psi=0.0,
            max_rounds=None):
    rng_t = np.random.default_rng(seed_truth)
    s = make_truth(rng_t, L, n, eta)
    topics = [Topic(int(x)) for x in s]
    rng = np.random.default_rng(seed_proto)
    if w == "n/4":
        w = n // 4
    probes = apply_probes(topics, rng, kind, n, phi, w, psi)
    R_T = sum(residual_bits(tp, kind, n, eta, phi, w, psi) for tp in topics)
    R_T_none = sum(residual_bits(Topic(tp.s), "none", n, eta, phi, w, psi) for tp in topics)
    bad = np.array([is_bad(tp, n) for tp in topics])
    nbad = int(bad.sum())
    task = 0
    checks = 0
    rounds = 0
    if max_rounds is None:
        max_rounds = 400 * L * n
    logn = math.ceil(math.log2(n))
    chunk = 1 << 16
    us = rng.random(chunk)
    ks = rng.random(chunk)
    ci = 0
    while nbad / L > eps and rounds < max_rounds:
        if ci == chunk:
            us = rng.random(chunk)
            ks = rng.random(chunk)
            ci = 0
        u, kr = us[ci], ks[ci]
        ci += 1
        rounds += 1
        l = int(u * L)  # topic of a uniform problem (two problems per topic)
        tp = topics[l]
        if proto == "MB":
            checks += 1
            while bad[l]:
                jd = write_step(tp, n)
                # first divergence of the decoder's run from the human's
                first = tp.s if jd is None else min(jd, tp.s)
                checks += logn + 1
                task += 1
                if first == tp.s:
                    tp.found = True
                    tp.content = True
                else:
                    tp.excl.add(first)
                b = is_bad(tp, n)
                if not b:
                    nbad -= 1
                bad[l] = b
            continue
        if proto != "CIall" and (tp.found or tp.none_known):
            continue  # the posterior is certain on this topic: no query
        if proto in ("CI", "CIall"):
            k = int(kr * n)
        elif proto == "LOC":
            if tp.region is not None and not tp.found:
                lo, hi = tp.region
                k = lo + int(kr * (hi - lo))
            else:
                k = int(kr * n)
        elif proto == "VER":
            if tp.content and tp.stated is not None and tp.stated not in tp.excl \
                    and not tp.found:
                k = tp.stated
            else:
                k = int(kr * n)
        else:
            raise ValueError(proto)
        task += 1
        jd = write_step(tp, n)
        if jd is not None and k > jd:
            continue  # the decoder's state carries a content: the human copies it
        # state (p, k, None): the answer says whether k is the stage (and the content)
        if tp.s < n and k == tp.s:
            tp.found = True
            tp.content = True
        else:
            tp.excl.add(k)
        b = is_bad(tp, n)
        if b != bad[l]:
            nbad += 1 if b else -1
            bad[l] = b
    return {"task": task, "checks": checks, "probes": probes, "rounds": rounds,
            "failure": nbad / L, "reached": nbad / L <= eps, "R_T": R_T,
            "R_T_noprobe": R_T_none, "techniques": int((s < n).sum())}


CONFIGS = [
    # label, probe kind, task protocol, params
    ("CI, asking every round (as E1)", "none", "CIall", {}),
    ("CI", "none", "CI", {}),
    ("MB (perfect check)", "none", "MB", {}),
    ("presence(1) + CI", "presence", "CI", {"phi": 1.0}),
    ("content(1) + CI", "content", "CI", {"phi": 1.0}),
    ("full(1)", "full", "CI", {"phi": 1.0}),
    ("full(0.9) + CI", "full", "CI", {"phi": 0.9}),
    ("full(0.5) + CI", "full", "CI", {"phi": 0.5}),
    ("window(1, w=8) + CI", "window", "CI", {"phi": 1.0, "w": 8}),
    ("window(1, w=8) + LOC", "window", "LOC", {"phi": 1.0, "w": 8}),
    ("window(1, w=n/4) + LOC", "window", "LOC", {"phi": 1.0, "w": "n/4"}),
    ("misreport(1, 0.2) + CI", "misreport", "CI", {"phi": 1.0, "psi": 0.2}),
    ("misreport(1, 0.2) + VER", "misreport", "VER", {"phi": 1.0, "psi": 0.2}),
    ("full(0.5) + MB (perfect check)", "full", "MB", {"phi": 0.5}),
]


def main(outdir):
    os.makedirs(outdir, exist_ok=True)
    L, eta, eps = 100, 0.5, 0.02
    ns = [16, 64, 256, 1024]
    humans = range(10)
    summary = {}
    for n in ns:
        for label, kind, proto, kw in CONFIGS:
            rows = []
            for h in humans:
                rows.append(run_one(5000 * n + h, 9 * 10**6 + 5000 * n + h, L, n, eta,
                                    eps, kind, proto, **kw))
            key = f"{label} | n={n}"
            summary[key] = {
                "n": n, "label": label,
                "reached": int(sum(r["reached"] for r in rows)), "humans": len(rows),
                "task_mean": float(np.mean([r["task"] for r in rows])),
                "task_median": float(np.median([r["task"] for r in rows])),
                "task_sem": float(np.std([r["task"] for r in rows], ddof=1)
                                  / math.sqrt(len(rows))),
                "probes_mean": float(np.mean([r["probes"] for r in rows])),
                "checks_mean": float(np.mean([r["checks"] for r in rows])),
                "final_failure_mean": float(np.mean([r["failure"] for r in rows])),
                "R_T_mean": float(np.mean([r["R_T"] for r in rows])),
                "R_T_noprobe_mean": float(np.mean([r["R_T_noprobe"] for r in rows])),
                "techniques_mean": float(np.mean([r["techniques"] for r in rows])),
            }
            print(json.dumps(summary[key]))
            sys.stdout.flush()
    with open(os.path.join(outdir, "threadB_kb_probes_summary.json"), "w") as f:
        json.dump(summary, f, indent=1)
    # table
    labels = [c[0] for c in CONFIGS]
    lines = ["| protocol | " + " | ".join(f"n = {n}" for n in ns) + " | R_T after probes (n = 16 / 1024) |",
             "|---|" + "---|" * len(ns) + "---|"]
    for lab in labels:
        cells = []
        for n in ns:
            e = summary[f"{lab} | n={n}"]
            c = f"{e['task_mean']:,.0f}"
            if e["reached"] < e["humans"]:
                c += f" ({e['reached']}/{e['humans']})"
            cells.append(c)
        r16 = summary[f"{lab} | n=16"]["R_T_mean"]
        r1k = summary[f"{lab} | n=1024"]["R_T_mean"]
        lines.append(f"| {lab} | " + " | ".join(cells) + f" | {r16:,.0f} / {r1k:,.0f} |")
    with open(os.path.join(outdir, "threadB_kb_probes_table.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "threadB_results")
