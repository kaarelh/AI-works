"""Write research/script-map.md: for every result of the two papers that rests on a computation,
the printed number (from main.aux) and the scripts behind it.

The working sources keep a \\status{...} tag and a \\src{...} note on each result (they print nothing
in the PDF). They name the research-track checks (checks/c*, checks/e*) and the independent
re-implementations (referee_code/r*, s*, q*). This script resolves those names to files.
Run from anywhere: python3 research/make_script_map.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRACKS = ['foundations', 'history', 'examples', 'context', 'steeper']
PAPERS = [('paper', 'Paper 1 (fundamentals)'), ('paper-steeper', 'Paper 2 (steeper simplicity priors)')]
ENV = {'theorem': 'Theorem', 'proposition': 'Proposition', 'lemma': 'Lemma', 'corollary': 'Corollary',
       'remark': 'Remark', 'example': 'Example', 'definition': 'Definition', 'conjecture': 'Conjecture',
       'question': 'Question', 'assumption': 'Assumption'}


def brace(s, i):
    depth = 0
    for j in range(i, len(s)):
        if s[j] == '{':
            depth += 1
        elif s[j] == '}':
            depth -= 1
            if depth == 0:
                return s[i + 1:j], j + 1
    return '', len(s)


def find_script(track, ident):
    sub = 'checks' if ident[0] in 'ce' else 'referee_code'
    hits = sorted(glob.glob(f'{ROOT}/research/tracks/{track}/{sub}/{ident}_*.py'))
    return [os.path.relpath(h, ROOT) for h in hits]


def scripts_in(status, src):
    """Resolve script ids. In the status tag an id belongs to the track named just before it
    ("computed (context c6(a))"). In the source note, ids after "check(s)" or "referee" belong to the
    note's own track, which is its first word ("foundations Prop 2.3 (= context ...); checks c6, r4")."""
    out = []
    track = None
    for tok in re.finditer(r'\b(foundations|history|examples|context|steeper)\b|\b([cersq]\d{1,2})(?![\d.])', status):
        if tok.group(1):
            track = tok.group(1)
        elif track:
            out.extend(find_script(track, tok.group(2)))
    first = re.match(r'\s*(foundations|history|examples|context|steeper)\b', src)
    home = first.group(1) if first else None
    for part in re.split(r';', src):
        m = re.search(r'\b(checks?|referee)\b(.*)', part)
        if m and home:
            ids = re.findall(r'\b([cersq]\d{1,2})(?![\d.])', m.group(2))
            named = re.search(r'\b(foundations|history|examples|context|steeper)\b', m.group(2))
            for i in ids:
                out.extend(find_script(named.group(1) if named else home, i))
        if 'T5 re-run' in part:
            out.append('research/tracks/steeper/checks/t5_rerun/')
    seen = []
    for o in out:
        if o not in seen:
            seen.append(o)
    return seen


lines = ['# Scripts behind the computed results', '',
         'Generated by `research/make_script_map.py` from the working sources of both papers. '
         'Each row is a result that states or uses a computed number, or whose statement was also checked by computer, '
         'with the scripts behind it. Scripts in `checks/` were written with the results; scripts in `referee_code/` '
         'are independent re-implementations. Each script is seeded or deterministic, and its output is saved next to it '
         '(`.out` or `.txt`).', '']
for paper, title in PAPERS:
    aux = open(f'{ROOT}/{paper}/main.aux').read()
    nums = {m.group(1): m.group(2) for m in re.finditer(r'\\newlabel\{([^}]*)\}\{\{([^}]*)\}', aux)}
    rows = []
    for f in sorted(glob.glob(f'{ROOT}/{paper}/sections/*.tex')):
        if 'app-verification' in f:
            continue
        s = re.sub(r'(?<!\\)%.*', '', open(f).read())
        for m in re.finditer(r'\\status\{', s):
            status, end = brace(s, m.end() - 1)
            src = ''
            m2 = re.match(r'\s*\\src\{', s[end:])
            if m2:
                src, _ = brace(s, end + m2.end() - 1)
            scripts = scripts_in(' '.join(status.split()), ' '.join(src.split()))
            if not scripts:
                continue
            begins = list(re.finditer(r'\\begin\{(\w+)\}', s[max(0, m.start() - 1500):m.start()]))
            env, label = None, None
            if begins and begins[-1].group(1) in ENV and not re.search(r'\\end\{' + begins[-1].group(1) + r'\}', s[max(0, m.start() - 1500) + begins[-1].end():m.start()]):
                env = begins[-1].group(1)
                start = max(0, m.start() - 1500) + begins[-1].start()
                lm = re.search(r'\\label\{([^}]*)\}', s[start:m.start() + 400])
                label = lm.group(1) if lm else None
            if not label:
                lm = list(re.finditer(r'\\label\{([^}]*)\}', s[:m.start()]))
                label = lm[-1].group(1) if lm else None
                env = None
            num = nums.get(label, '?')
            if env:
                name = f'{ENV[env]} {num}'
            elif label and label.startswith(('sec:', 'app:')):
                name = f'Section {num}' if not num[:1].isalpha() else f'Appendix {num}'
            else:
                name = f'(near) {num}'
            rows.append((name, label or '', scripts))
    lines += [f'## {title}', '', '| result | label | scripts |', '|---|---|---|']
    for name, label, scripts in rows:
        lines.append(f'| {name} | `{label}` | ' + '<br>'.join(f'`{x}`' for x in scripts) + ' |')
    lines.append('')
open(f'{ROOT}/research/script-map.md', 'w').write('\n'.join(lines))
print(sum(1 for l in lines if l.startswith('| ') and not l.startswith('| result')), 'rows')
