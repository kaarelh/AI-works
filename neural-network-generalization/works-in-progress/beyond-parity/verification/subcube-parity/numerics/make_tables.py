"""Write results.md from the run summaries in this folder.

Reads runs/*.json (gd_train2.py summaries), jobs.txt (the queue; entries without a summary are
listed as pending) and the logs in round1-default-init/runs*/ (gd_train.py, whose logs record no
settings; the settings below are the command lines that produced them).
Usage: python3 -I make_tables.py      (writes results.md next to this script; reads nothing else)
"""
import glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
THR = 0.05

TARGETS = {
    "mix": "staircase-or-parity target: sign(x_1 + x_1x_2 + ... + x_1...x_d) if z=+1, x_1...x_d if z=-1",
    "ctrl": "control: x_1 if z=+1, x_1...x_d if z=-1",
    "mixw": "weighted variant: sign(x_1 + ... + x_1...x_{d-1} + 5 x_1...x_d) if z=+1, x_1...x_d if z=-1 (d=31)",
    "par": "full parity x_1...x_d",
    "stair": "sign-staircase sign(x_1 + x_1x_2 + ... + x_1...x_d)",
}
INITS = {
    "gaussian": "every weight N(0, 1/fan_in), every bias 0",
    "gaussianU": "weights N(0, 1/fan_in), biases PyTorch default U(-1/sqrt(fan_in), 1/sqrt(fan_in))",
    "gaussian3": "weights N(0, 1/(3 fan_in)) (the variance of PyTorch's default), biases 0",
    "gaussian3U": "weights N(0, 1/(3 fan_in)), biases PyTorch default",
    "default0": "PyTorch default weights U(-1/sqrt(fan_in), 1/sqrt(fan_in)), biases 0",
    "default": "PyTorch default (weights and biases U(-1/sqrt(fan_in), 1/sqrt(fan_in)))",
    "rademacher": "first-layer weights +-1/sqrt(fan_in), other layers PyTorch default",
}

# Round-1 command lines: gd_train.py target d steps seed [width depth lr batch init arch]
R1 = {
    "runs/ctrl_31": "ctrl 31 20000 0", "runs/mix_31": "mix 31 20000 0",
    "runs/par_31": "par 31 20000 0", "runs/stair_31": "stair 31 20000 0",
    "runs2/mix_21": "mix 21 60000 1", "runs2/mix_25": "mix 25 60000 1",
    "runs2/mix_31": "mix 31 80000 1", "runs2/stair_31": "stair 31 60000 1",
    "runs2/mix41_2layer": "mix 41 40000 3 1024 1 1e-3 512 default",
    "runs2/stair41_2layer": "stair 41 40000 3 1024 1 1e-3 512 default",
    "runs3/ctrl_21": "ctrl 21 30000 1",
    "runs3/ctrl_31_long": "ctrl 31 120000 4", "runs3/mix_31_long": "mix 31 120000 4",
    "runs3/mixw_31_long": "mixw 31 120000 4",
    "runs4/mix_27_trunk": "mix 27 60000 5 512 3 1e-3 512 default trunk",
    "runs4/ctrl_27_trunk": "ctrl 27 60000 5 512 3 1e-3 512 default trunk",
    "runs4/mix_31_trunk": "mix 31 100000 5 512 3 1e-3 512 default trunk",
    "runs4/ctrl_31_trunk": "ctrl 31 100000 5 512 3 1e-3 512 default trunk",
}
for dd in (20, 30, 40, 50):
    for ini in ("default", "rademacher"):
        R1[f"runs2/par{dd}_2layer_{ini}"] = f"par {dd} 30000 2 1024 1 1e-3 512 {ini}"


def fn(x):
    """Sample counts as 1.23e7."""
    if x is None:
        return "–"
    m, e = f"{float(x):.2e}".split("e")
    return f"{m}e{int(e)}"


def fe(x):
    return "–" if x is None else f"{x:.4f}"


def arch_str(arch, depth, width, target=None):
    if arch != "trunk":
        return f"MLP {depth}×{width}"
    # par and stair have no selector bit, so the trunk then has a single readout
    return f"{'one-head trunk' if target in ('par', 'stair') else 'two-head trunk'} {depth}×{width}"


def r1_parse(cmd):
    v = cmd.split()
    t, d, steps, seed = v[0], int(v[1]), int(v[2]), int(v[3])
    width = int(v[4]) if len(v) > 4 else 512
    depth = int(v[5]) if len(v) > 5 else 3
    lr = float(v[6]) if len(v) > 6 else 1e-3
    batch = int(v[7]) if len(v) > 7 else 512
    init = v[8] if len(v) > 8 else "default"
    arch = v[9] if len(v) > 9 else "mlp"
    return dict(target=t, d=d, steps=steps, seed=seed, width=width, depth=depth, lr=lr,
                batch=batch, init=init, arch=arch)


out = []
w = out.append

# ---------------- round-2 summaries ----------------
runs = []
for js in sorted(glob.glob(os.path.join(HERE, "runs", "*.json"))):
    S = json.load(open(js))
    runs.append((os.path.basename(js)[:-5], S))
names_done = {n for n, _ in runs}
jobs = []
for ln in open(os.path.join(HERE, "jobs.txt")):
    ln = ln.strip()
    if ln and not ln.startswith("#"):
        n, a = [s.strip() for s in ln.split("|", 1)]
        jobs.append((n, a))
pending = [(n, a) for n, a in jobs if n not in names_done]

w("# GD numerics: results tables\n")
w("Generated by `make_tables.py` from the files in this folder. Do not edit by hand.\n")
w("**Status: numerical.** Single runs, mostly one seed each, at $`19\\le d\\le 50`$. "
  "These dimensions cannot distinguish polynomial from exponential growth in $`d`$.\n")
w("## Targets\n")
for k, v in TARGETS.items():
    w(f"- `{k}`: {v}.")
w("\nThe input is $`(x,z)`$ with $`x\\in\\lbrace -1,1\\rbrace ^d`$ and one selector bit $`z`$ for the two-half "
  "targets, so $`D=d+1`$ input bits; $`D=d`$ for `par` and `stair`. Inputs are uniform.\n")
w("## Architectures and initializations\n")
w("- **two-head trunk** depth×width: a ReLU MLP on $`x`$ only, with output $`a\\cdot h(x)+z\\,b\\cdot h(x)`$; "
  "$`z`$ only selects the readout. For `par` and `stair`, which have no $`z`$, the same trunk has the single "
  "readout $`a\\cdot h(x)`$ (**one-head trunk**).")
w("- **MLP** depth×width: a plain ReLU MLP on all $`D`$ input bits, so $`z`$ is an ordinary input.")
w("- All layers are `torch.nn.Linear`, with biases. Initializations:")
for k, v in INITS.items():
    w(f"  - `{k}`: {v}.")
w("")

w("## Gaussian-initialization runs (`gd_train2.py`)\n")
w(f"Common settings: square loss on $`\\pm1`$ labels, batch 512, fresh uniform samples at every step "
  f"(online training, so samples = steps × 512). The test set has 20000 points drawn once from a separate "
  f"seeded generator (10000 in each $`z`$-half for two-half targets). Any training point that coincides "
  f"with a test point is resampled, so the test points are never trained on. Errors are sign errors on the "
  f"test set. Evaluation every 100 steps up to step 2000 and every 500 steps after. "
  f"\"Samples to {THR}\" is the first evaluation at which that error is less than {THR} (errors are computed "
  f"in single precision, so an error of exactly {THR} does not count). "
  f"A run stops early (\"early\") once every tracked error (both halves, or the single error) has been "
  f"less than {THR} at 3 consecutive evaluations; otherwise it runs to its budget (\"cap\"). "
  f"\"Final\" is the last evaluation. Optimizer: Adam, learning rate 1e-3, unless stated.\n")

two = [(n, S) for n, S in runs if S["args"]["target"] in ("mix", "ctrl")]
one = [(n, S) for n, S in runs if S["args"]["target"] not in ("mix", "ctrl")]


def key(item):
    a = item[1]["args"]
    return (a["target"], a["arch"], a["depth"], a["width"], a["init"], a["opt"], a["d"], a["seed"])


def opt_str(a):
    return "Adam 1e-3" if (a["opt"], a["lr"]) == ("adam", 1e-3) else \
        f"{a['opt']} {a['lr']:g}" + (f" mom {a['momentum']:g}" if a.get("momentum") else "")


if two:
    w("### Two-half targets\n")
    w(f"`zneg` is the parity half $`z=-1`$, `zpos` the other half, `all` the whole test set.\n")
    w(f"| run | target | d | architecture | init | optimizer | seed | budget | samples to {THR}: zneg | zpos | all "
      f"| final samples | final err: all | zneg | zpos | stop |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for n, S in sorted(two, key=key):
        a, h, f = S["args"], S["hit_samples"], S["final"]
        w(f"| `{n}` | `{a['target']}` | {a['d']} | {arch_str(a['arch'], a['depth'], a['width'], a['target'])} | `{a['init']}` "
          f"| {opt_str(a)} | {a['seed']} | {fn(a['max_samples'])} | {fn(h.get('zneg'))} | {fn(h.get('zpos'))} "
          f"| {fn(h.get('all'))} | {fn(f['samples'])} | {fe(f.get('err_all'))} | {fe(f.get('err_zneg'))} "
          f"| {fe(f.get('err_zpos'))} | {'early' if S['stopped_early'] else 'cap'} |")
    w("")
if one:
    w("### Single targets\n")
    w(f"| run | target | d | architecture | init | optimizer | seed | budget | samples to {THR} "
      f"| final samples | final err | stop |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for n, S in sorted(one, key=key):
        a, h, f = S["args"], S["hit_samples"], S["final"]
        w(f"| `{n}` | `{a['target']}` | {a['d']} | {arch_str(a['arch'], a['depth'], a['width'], a['target'])} | `{a['init']}` "
          f"| {opt_str(a)} | {a['seed']} | {fn(a['max_samples'])} | {fn(h.get('all'))} | {fn(f['samples'])} "
          f"| {fe(f.get('err_all'))} | {'early' if S['stopped_early'] else 'cap'} |")
    w("")
if runs:
    w("### Run details\n")
    w("Wall time is on a shared machine running two jobs at once. At small $`D`$ the 20000 test draws contain "
      "repeats, and many training draws hit the test set and are resampled.\n")
    w("| run | wall time (s) | resampled training points | distinct test points | parameters |")
    w("|---|---|---|---|---|")
    for n, S in sorted(runs, key=key):
        w(f"| `{n}` | {S['wall_s']:.0f} | {S['rejected_train_points']} | {S['distinct_test_points']} "
          f"| {S['args']['n_params']} |")
    w("")
w("### Pending\n")
if pending:
    w("These entries of `jobs.txt` have no summary in `runs/` yet (queued, running, or interrupted). "
      "They are left out of the tables above.\n")
    for n, a in pending:
        w(f"- `{n}`: `{a}`")
else:
    w("None: every entry of `jobs.txt` has a summary.")
w("")

# ---------------- round-1 logs ----------------
w("## PyTorch-default-initialization runs (`round1-default-init/gd_train.py`)\n")
w("Common settings: square loss, Adam, learning rate 1e-3, batch 512, fresh uniform samples at every step, "
  "40 evaluations evenly spaced over the planned steps. The test set is 20000 uniform points drawn once; "
  "unlike the runs above, training points are **not** kept off the test set. At $`D\\le 22`$ "
  "($`2^{22}\\approx4.2\\cdot10^6`$ inputs) a run of $`10^7`$ samples has seen most test points, so the "
  "small-$`d`$ test errors there partly measure memorization. \"Samples to 0.05\" is read off the coarse "
  "evaluation grid. Runs whose log ends before the planned number of steps were stopped by hand "
  "(\"stopped\").\n")
w("| log | target | d | architecture | init | seed | budget | samples to 0.05: zneg | zpos | all "
  "| final samples | final err: all | zneg | zpos | stop |")
w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
pat = re.compile(r"step (\d+) samples ([0-9.e+]+) test_err ([0-9.]+)(?: err_zneg ([0-9.]+) err_zpos ([0-9.]+))?")
rows = []
for name, cmd in R1.items():
    fp = os.path.join(HERE, "round1-default-init", name + ".txt")
    if not os.path.exists(fp):
        continue
    a = r1_parse(cmd)
    ev = [m.groups() for m in map(pat.match, open(fp).read().splitlines()) if m]
    hit = {}
    for st, smp, ea, en, ep in ev:
        for k, v in (("all", ea), ("zneg", en), ("zpos", ep)):
            if v is not None and float(v) <= THR and k not in hit:
                hit[k] = float(smp)
    st, smp, ea, en, ep = ev[-1]
    stop = "cap" if int(st) == a["steps"] else "stopped"
    rows.append(((a["target"], a["arch"], a["depth"], a["init"], a["d"], a["seed"], name),
                 f"| `{name}.txt` | `{a['target']}` | {a['d']} | {arch_str(a['arch'], a['depth'], a['width'], a['target'])} "
                 f"| `{a['init']}` | {a['seed']} | {fn(a['steps'] * a['batch'])} | {fn(hit.get('zneg'))} "
                 f"| {fn(hit.get('zpos'))} | {fn(hit.get('all'))} | {fn(float(smp))} | {fe(float(ea))} "
                 f"| {fe(None if en is None else float(en))} | {fe(None if ep is None else float(ep))} | {stop} |"))
for _, r in sorted(rows):
    w(r)
w("")
w("For single targets the `all` columns are the only ones. Exact command lines are in `make_tables.py` (`R1`).\n")

open(os.path.join(HERE, "results.md"), "w").write("\n".join(out))
print(f"wrote results.md: {len(runs)} summaries, {len(pending)} pending, {len(rows)} round-1 logs")
