"""Referee check R5: property tests of Min(D) (dtrc.mincover) on random DT°_F templates in both languages.
 (b) E1(c): if D is a subset of inst(T*) with T* in DT°_F (no rigid parameters), some computed min is <= T*.
 (a) every computed min covers D, is DT°, has 0-ary term metas; mins pairwise incomparable.
 (c) minimality: random one-step specialisations of a computed min that still cover D must be equivalent to it.
Templates are generated by the referee's own generator (random skeleton, metavariable leaves with a pattern
first occurrence and arbitrary metavariable-free later occurrences)."""
import sys, random, itertools, time
sys.path.insert(0, '/home/user/AI-works/axiom-schemas/code')
from dtrc.syntax import (pp, canon_params, kids, rebuild, LEAVES, BINDERS, free_indices, plug, shift, H, P,
                         ZERO, S)
from dtrc.templates import (instantiate, match, geq, equiv, is_DT0, covers_all, metas, meta_occurrences, canon)
from dtrc.mincover import MinCover
from dtrc.datasets import rand_zf_formula, rand_pa_formula, rand_closed_term

def rterm_pa(rng, nb, d=1):
    opts = ['0', '0', 'v'] if nb else ['0']
    k = rng.choice(opts + ['S', '+'] if d > 0 else opts)
    if k == '0': return ZERO
    if k == 'v': return ('v', rng.randrange(nb))
    if k == 'S': return S(rterm_pa(rng, nb, d - 1))
    return ('+', rterm_pa(rng, nb, d - 1), rterm_pa(rng, nb, d - 1))

def rvar_zf(rng, nb):
    return ('v', rng.randrange(nb)) if nb else P('c')

def gen_template(rng, lang, depth, nb, metas_, budget):
    """metas_: dict name -> (sort, arity, has_pattern) ; occurrences appended"""
    r = rng.random()
    if depth <= 0 or r < 0.25:
        # leaf: atom or formula metavariable occurrence
        if rng.random() < 0.5 and budget[0] > 0:
            # metavariable occurrence: reuse or new
            fm = [m for m, v in metas_.items() if v[0] == 'F']
            if fm and rng.random() < 0.5:
                m = rng.choice(fm); ar = metas_[m][1]
                if metas_[m][2] or nb < ar:
                    args = tuple(rterm_pa(rng, nb) if lang == 'PA' else rvar_zf(rng, nb) for _ in range(ar))
                else:
                    args = tuple(('v', i) for i in rng.sample(range(nb), ar)); metas_[m][2] = True
                return ('M', m, args)
            budget[0] -= 1
            m = 'P%d' % len(metas_)
            ar = rng.randint(0, min(2, nb))
            metas_[m] = ['F', ar, True]
            return ('M', m, tuple(('v', i) for i in rng.sample(range(nb), ar)))
        if lang == 'PA':
            a = rterm_pa(rng, nb)
            if rng.random() < 0.3 and budget[0] > 0:
                tm = [m for m, v in metas_.items() if v[0] == 'T']
                if tm and rng.random() < 0.5: m = rng.choice(tm)
                else:
                    budget[0] -= 1; m = 'f%d' % len(metas_); metas_[m] = ['T', 0, True]
                a = ('+', a, ('M', m, ())) if rng.random() < 0.5 else ('M', m, ())
            return (rng.choice(['=', '<']), a, rterm_pa(rng, nb))
        return (rng.choice(['in', '=']), rvar_zf(rng, nb), rvar_zf(rng, nb))
    k = rng.choice(['not', 'and', 'or', 'imp', 'iff', 'all', 'ex', 'all', 'ex'])
    if k == 'not': return ('not', gen_template(rng, lang, depth - 1, nb, metas_, budget))
    if k in ('all', 'ex'): return (k, gen_template(rng, lang, depth - 1, nb + 1, metas_, budget))
    return (k, gen_template(rng, lang, depth - 1, nb, metas_, budget), gen_template(rng, lang, depth - 1, nb, metas_, budget))

def rbody(rng, lang, sort, ar):
    if sort == 'T':
        return rand_closed_term(rng, 2, params=('a',)) if rng.random() < 0.8 else P('b')
    for _ in range(50):
        if lang == 'PA':
            b = rand_pa_formula(rng, 0, rng.choice([[], ['a']]), rng.randint(0, 2), nholes=max(ar, 1))
        else:
            b = rand_zf_formula(rng, max(ar, 1), 0, rng.choice([['c'], ['c', 'd']]), rng.randint(0, 2))
        if ar == 0 and any(h[0] == 'h' for _, h in __import__('dtrc.syntax', fromlist=['positions']).positions(b)):
            continue
        return b
    return ('=', ZERO, ZERO) if lang == 'PA' else ('in', P('c'), P('c'))

def specialisations(M, D, rng, lang):
    """one-step specialisations of template M that may still cover D"""
    out = []
    ths = [match(M, d) for d in D]
    ms = metas(M)
    for m, ar in ms.items():
        bodies = [th[m] for th in ths]
        h0 = bodies[0][0]
        # (1) head push-down when all bodies share a connective head
        if all(b[0] == h0 for b in bodies) and h0 in ('not', 'and', 'or', 'imp', 'iff', 'all', 'ex'):
            holes = tuple(H(i) for i in range(ar))
            if h0 in BINDERS:
                new = (h0, ('M', m + 'a', (('v', 0),) + tuple(shift(h, 1) for h in holes)))
            else:
                new = (h0,) + tuple(('M', m + 'abc'[i], holes) for i in range(len(bodies[0]) - 1))
            out.append(instantiate(M, {**{x: _idbody(x, a) for x, a in ms.items()}, m: _lift(new)}))
        # (2) body equals a fixed metavariable-free formula/term in all data -> rigid
        if all(b == bodies[0] for b in bodies) and not any(t[0] == 'h' for t in _subterms(bodies[0])):
            out.append(instantiate(M, {**{x: _idbody(x, a) for x, a in ms.items()}, m: bodies[0]}))
        # (3) drop a hole unused in every body
        for i in range(ar):
            if not any(('h', i) in set(_subterms(b)) for b in bodies):
                keep = tuple(H(j) for j in range(ar) if j != i)
                out.append(instantiate(M, {**{x: _idbody(x, a) for x, a in ms.items()}, m: ('M', m + 'd', keep)}))
        # (4) identify with another metavariable of the same sort and arity (holes permuted)
        for m2, ar2 in ms.items():
            if m2 != m and ar2 == ar and m[0].isupper() == m2[0].isupper():
                for perm in itertools.permutations(range(ar)):
                    out.append(instantiate(M, {**{x: _idbody(x, a) for x, a in ms.items()},
                                               m: ('M', m2, tuple(H(j) for j in perm))}))
    return out

def _subterms(t):
    yield t
    if t[0] in LEAVES: return
    for k in kids(t): yield from _subterms(k)

def _idbody(name, ar):
    return ('M', name, tuple(H(i) for i in range(ar)))

def _lift(new):
    return new

def run(lang, n, seed):
    rng = random.Random(seed)
    st = dict(sets=0, b_fail=0, a_fail=0, c_viol=0, c_tested=0, mins=0, trunc=0, skipped=0)
    ex = []
    t0 = time.time()
    while st['sets'] < n:
        metas_ = {}
        T = gen_template(rng, lang, rng.randint(2, 4), 0, metas_, [3])
        if not metas(T) or not is_DT0(T):
            st['skipped'] += 1; continue
        ms = metas(T)
        D = []
        wraps = {m: rng.choice([None, None, 'not', 'and', 'imp', 'all', 'shared']) for m in ms}
        shared = {m: rbody(rng, lang, 'F' if m[0].isupper() else 'T', a) for m, a in ms.items()}
        for _ in range(rng.randint(2, 3)):
            th = {}
            for m, a in ms.items():
                srt = 'F' if m[0].isupper() else 'T'
                b = rbody(rng, lang, srt, a)
                w = wraps[m]
                if srt == 'F' and w == 'not': b = ('not', b)
                elif srt == 'F' and w in ('and', 'imp'): b = (w, shared[m], b)
                elif srt == 'F' and w == 'all': b = ('all', shift(b, 1))
                elif srt == 'T' and w in ('not', 'and'): b = S(b)
                th[m] = b
            D.append(canon_params(instantiate(T, th)))
        D = list(dict.fromkeys(D))
        if len(D) < 2 or not covers_all(T, D):
            st['skipped'] += 1; continue
        mc = MinCover(D); mins = mc.minimal()
        st['sets'] += 1; st['mins'] += len(mins); st['trunc'] += int(mc.truncated)
        if not any(geq(T, M) for M in mins):
            st['b_fail'] += 1
            if len(ex) < 4: ex.append(('E1c', pp(T), [pp(d) for d in D], [pp(M) for M in mins]))
        for M in mins:
            if not (covers_all(M, D) and is_DT0(M) and all(a == 0 for m, a in metas(M).items() if m[0].islower())):
                st['a_fail'] += 1
        for M1, M2 in itertools.combinations(mins, 2):
            if geq(M1, M2) or geq(M2, M1):
                st['a_fail'] += 1
        for M in mins:
            for Tp in specialisations(M, D, rng, lang):
                if not is_DT0(Tp) or not covers_all(Tp, D):
                    continue
                if any(a > 0 for m, a in metas(Tp).items() if m[0].islower()):
                    continue
                st['c_tested'] += 1
                if not geq(Tp, M):
                    st['c_viol'] += 1
                    if len(ex) < 8: ex.append(('minimality', pp(M), pp(Tp), [pp(d) for d in D]))
    print(lang, st, '%.0fs' % (time.time() - t0))
    for e in ex: print('  ', e)

if __name__ == '__main__':
    run(sys.argv[1], int(sys.argv[2]), int(sys.argv[3]))
